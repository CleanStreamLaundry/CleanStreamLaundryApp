import test from 'node:test';
import assert from 'node:assert/strict';
import { access } from 'node:fs/promises';
import { createHash } from 'node:crypto';

import { disposableCluster } from './test-support/policy-admission-pg.mjs';
import { read } from './test-support/account-cleanup.mjs';
import { exerciseLifecycle, exercisePopulatedRelations } from './test-support/account-cleanup-execution.mjs';
import { exerciseBoundaries } from './test-support/account-cleanup-boundaries.mjs';
import { exercisePaidCreditPreservation } from './test-support/account-cleanup-paid-credit.mjs';
import { exerciseNinetyDayRecovery } from './test-support/account-recovery-ninety-days.mjs';
import { exerciseVoluntarySurrender } from './test-support/account-credit-surrender.mjs';
import { exerciseFactualCleanupInventory } from './test-support/account-cleanup-factual-inventory.mjs';

const migration = (n) => read(`supabase/migrations/${n}.sql`);
const first = '20261001130137_permanent_account_cleanup';
const second = '20261001130950_retained_financial_subjects';

test('cleanup installation on catalog-matched prerequisites, stop on first defect', { timeout: 150000 }, async (t) => {
  const cluster = await disposableCluster(t, process.env.PG_BIN);
  const deadline = setTimeout(() => process.kill(process.pid, 'SIGTERM'), 155000);
  const db = await cluster.connect();
  const run = async (sql) => {
    const s = await cluster.connect();
    try { return await s.query(sql); } finally { await s.close(); }
  };
  const check = async (name, action) => {
    let passed = false;
    await t.test(name, async () => { await action(); passed = true; });
    assert(passed, `Stopped at first failed check: ${name}`);
  };
  const install = async (name) => {
    const sql = await migration(name);
    t.diagnostic(`SOURCE ${name} sha256=${createHash('sha256').update(sql).digest('hex')}`);
    await db.query(sql);
  };
  try {
    // Same financial/admission foundation as customer-mfa-recovery.test.mjs.
    await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
    await db.query((await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS')[0]);
    for (const n of ['20260526010000_wallet_ledger_compliance', '20260803150427_cortina_qr_remote_vend',
      '20260807191723_harden_refund_resolution', '20260929231120_serialize_wallet_financial_writes']) await install(n);
    await db.query(`grant execute on function public.is_admin_or_owner() to authenticated;
      create trigger handle_transaction after insert on public.transactions for each row execute function public.update_user_balance();`);
    for (const n of ['20260807195409_configure_dryer_time_options', '20260922224735_cortina_price_array_selectors',
      '20260928132533_link_cortina_transaction_history']) await install(n);
    await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
      add column is_anonymous boolean default false, add column banned_until timestamptz,
      add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
      add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz,
      add column created_at timestamptz default now();
      alter table public.profiles add column created_at timestamptz default now();
      alter table public."Location_to_Admin" enable row level security;
      alter table public."Refunds" drop constraint "Refunds_user_id_fkey",
        add constraint "Refunds_user_id_fkey1" foreign key(user_id) references public.profiles(id) on update cascade on delete cascade;
      alter table public."Refunds" alter column user_id set not null;`);
    for (const n of ['20260929223124_protect_profile_authority', '20260929234955_loyalty_policy_acceptance']) await install(n);
    await db.query(await read('supabase/tests/account_admission.fixture.sql'));
    for (const n of ['20260930005456_account_admission', '20260930013417_enforce_profile_terms_admission',
      '20260930024142_protect_location_membership', '20260930063923_recoverable_account_deletion',
      '20260930125554_voluntary_topup_refunds']) await install(n);
    await db.query(`alter table public."Locations" alter column id add generated by default as identity,
      add column "Name" text, add column "Address" text, add column "Latitude" double precision, add column "Longitude" double precision;
      alter table public."Machines" add column "Runtime" integer, add column "Status" text;
      alter table public."Refunds" add column date timestamptz default now();`);
    // Preserve the verified composite PK, not the looser admin fixture stand-in.
    const maintenance = await read('supabase/tests/maintenance_authorization.fixture.sql');
    const definition = maintenance.match(/create table public\."Maintenance" \([\s\S]*?\n\);/);
    assert(definition);
    const authRole = maintenance.match(/^create function auth\.role\(\).*\$\$;$/gm);
    assert.equal(authRole?.length, 1, 'Reuse the intact fixture Auth role helper exactly once');
    await db.query(authRole[0]);
    await db.query(`${definition[0]} alter table public."Maintenance" enable row level security;`);
    for (const n of ['20260928135006_admin_portal_operations', '20260928151021_admin_operations_extensions',
      '20260930032327_maintenance_authorization', '20260930131557_admin_collection_reporting',
      '20260930142406_admin_canonical_authorization', '20260930202731_customer_mfa_recovery',
      '20260930125527_newsletter_consent_mail_outbox', '20260930130013_push_token_registration',
      '20261001011048_push_registration_bounds', '20260930154911_account_cleanup_claims']) await install(n);
    await db.query(`create role supabase_storage_admin nologin nosuperuser;
      grant usage on schema auth to supabase_storage_admin;`);
    const storageStart = 'create schema storage authorization';
    assert.equal(maintenance.split(storageStart).length - 1, 1);
    await db.query(maintenance.slice(maintenance.indexOf(storageStart)));
    // The supplied catalog has this nullable clock with now() default; the older
    // attachment fixture predates cleanup's authoritative closure comparison.
    await db.query(`set role supabase_storage_admin;
      alter table storage.objects add column created_at timestamptz default now(); reset role;`);
    await db.query(`grant usage,create on schema public to postgres; grant usage on schema auth to postgres;
      grant select(id,email,created_at,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id),references(id),trigger on auth.users to postgres;
      grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
      grant select(id,user_id,factor_type,status,created_at) on auth.mfa_factors to postgres;
      alter role postgres nosuperuser bypassrls; set role postgres;`);
    // Inspect all external relation/column and function dependencies together
    // before either candidate, rather than repairing one loader failure per run.
    const requiredColumns = {
      'auth.users': 'id email',
      'public.profiles': 'id reward_tracker',
      'public."Maintenance"': 'maint_id user_id created_at status description location image_data attachment_ref',
      'public.admin_maintenance_history': 'id maintenance_id actor_id actor_name from_status to_status note created_at',
      'public.admin_invitations': 'invited_by user_id',
      'storage.objects': 'id bucket_id name owner owner_id version created_at archived_at is_delete_marker is_versioned',
      'private.account_lifecycle': 'user_id deletion_requested_at restore_until restored_at',
      'private.account_cleanup_jobs': 'user_id deletion_requested_at claim_id attempts used_claim_ids state lease_until retry_after',
      'private.push_installations': 'user_id',
      'private.push_creation_budget': 'user_id',
      'private.customer_mfa_recovery': 'user_id recovery_id started_at',
      'private.mail_outbox': 'id user_id kind state email consent_id last_error',
      'private.mail_suppression': 'email reason',
      'private.newsletter_consent': 'id user_id email confirm_hash unsubscribe_hash unsubscribed_at suppression_reason confirmed_at requested_at',
      'public.wallet_accounts': 'id user_id',
      'public.wallet_loads': 'id user_id wallet_account_id amount_cents paid_amount_cents promo_amount_cents stripe_payment_intent_id stripe_checkout_session_id stripe_charge_id stripe_event_id status note',
      'public.wallet_redemptions': 'user_id',
      'public.wallet_ledger_entries': 'created_by wallet_account_id entry_type amount_cents paid_amount_cents promo_amount_cents wallet_load_id stripe_payment_intent_id stripe_charge_id voluntary_topup_refund_id note',
      'public.transactions': 'user_id',
      'public."Refunds"': 'user_id',
      'public.cortina_vend_sessions': 'user_id',
      'private.topup_refund_provenance': 'load_id reward_before_cents',
      'private.voluntary_topup_refunds': 'id customer_id reviewed_by wallet_id principal_cents load_id released_at',
    };
    const columnChecks = Object.entries(requiredColumns).flatMap(([relation, names]) =>
      names.split(' ').map(column => ({ relation, column })));
    const missingColumns = await db.query(`select coalesce(jsonb_agg(r),'[]')
      from jsonb_to_recordset('${JSON.stringify(columnChecks)}'::jsonb) r(relation text,"column" text)
      where not exists(select 1 from pg_attribute a where a.attrelid=to_regclass(r.relation)
        and a.attname=r."column" and a.attnum>0 and not a.attisdropped);`);
    assert.deepEqual(JSON.parse(missingColumns), [], 'All missing cleanup prerequisite columns');
    const signatures = [
      'auth.role()', 'public.restore_account()', 'public.claim_account_cleanup(uuid,timestamptz,uuid)',
      'public.retry_account_cleanup(uuid,timestamptz,uuid,text)', 'public.preview_account_cleanup(integer,uuid)',
      'private.portal_audit_immutable()', 'private.mail_lock()',
      'public.get_or_create_wallet_account(uuid)', 'public.sync_profile_wallet_balance(uuid)',
      'public.record_wallet_load_from_stripe(uuid,integer,text,text,text,text)',
      'private.capture_topup_refund_provenance()', 'private.release_topup_refund(uuid)',
    ];
    assert.deepEqual(JSON.parse(await db.query(`select coalesce(jsonb_agg(signature),'[]')
      from jsonb_array_elements_text('${JSON.stringify(signatures)}'::jsonb) s(signature)
      where to_regprocedure(signature) is null;`)), [], 'All missing cleanup prerequisite functions');
    assert.equal(await db.query(`select count(*) from pg_constraint
      where conrelid='private.account_cleanup_jobs'::regclass and conname='account_cleanup_jobs_state_check';`), '1');
    assert.equal(await db.query(`select has_table_privilege('postgres','auth.users','TRIGGER')
      and has_column_privilege('postgres','auth.users','id','REFERENCES')
      and has_table_privilege('postgres','storage.objects','SELECT');`), 't');
    await check('prerequisites preserve Maintenance composite PK and all 12 exact original FK signatures', async () => {
      assert.equal(await db.query(`select pg_get_constraintdef(oid) from pg_constraint
        where conrelid='public."Maintenance"'::regclass and contype='p';`), 'PRIMARY KEY (user_id, created_at)');
      const source = await migration(second);
      const tuples = [...source.matchAll(/\('([^']+)','([^']+)','([^']+)','([^']+)','([^']+)'\)/g)];
      assert.equal(tuples.length, 12);
      for (const [, schema, table, column, name, parent] of tuples) {
        assert.equal(await db.query(`select count(*) from pg_constraint c join pg_attribute a
          on a.attrelid=c.conrelid and a.attname='${column}'
          where c.conrelid='${schema}."${table}"'::regclass and c.conname='${name}'
            and c.contype='f' and c.convalidated and not c.condeferrable
            and c.confrelid='${parent}'::regclass and c.conkey=array[a.attnum]::smallint[]
            and c.confkey=array[(select attnum from pg_attribute where attrelid=c.confrelid and attname='id')]::smallint[];`), '1', name);
      }
      assert.equal(await db.query("select rolsuper from pg_roles where rolname=current_user;"), 'f');
    });
    await check('unchanged permanent cleanup migration installs as nonsuperuser postgres', async () => { await install(first); });
    await check('installation leaves execution disabled and rejects service executor before any dispatch', async () => {
      assert.equal(await db.query('select execution_enabled or credit_forfeiture_enabled from private.account_cleanup_execution;'), 'f');
      await assert.rejects(run(`set role service_role; select public.execute_account_cleanup_step(
        '00000000-0000-4000-8000-000000000021','retention-draft-2026-10-01',
        '3e14877eed8a552cef4fd5c7f2183d98d42897dbcb7bf2c3496b3ebcbd67c6be');`), e => {
        assert.equal(e.code, 'PT503', e.message); assert.match(e.message, /cleanup_policy_unapproved/); return true;
      });
    });
    const before = await db.query(`select jsonb_agg(jsonb_build_array(oid,conname,pg_get_constraintdef(oid)) order by oid)
      from pg_constraint where contype='f';`);
    await check('unchanged retained-subject migration installs without weakening the real Maintenance key', async () => {
      try { await install(second); }
      catch (error) {
        t.diagnostic(`FIRST PRODUCT FAILURE: SQLSTATE ${error.code}: ${error.message}`);
        const after = await run(`select jsonb_agg(jsonb_build_array(oid,conname,pg_get_constraintdef(oid)) order by oid)
          from pg_constraint where contype='f';`);
        assert.equal(after, before, 'Failed reference migration must roll back every FK replacement');
        t.diagnostic('ROLLBACK VERIFIED: every original FK OID/name/definition unchanged');
        throw error;
      }
    });
    if (process.env.RECOVERY_90_DAY_ONLY === '1' || process.env.CREDIT_SURRENDER_ONLY === '1'
      || process.env.FACTUAL_CLEANUP_INVENTORY_ONLY === '1') {
      await db.query('revoke all on function public.request_account_deletion() from public,anon,authenticated,service_role;');
      for (const n of ['20260930213402_canonical_admin_onboarding', '20261001013709_owner_management',
        '20261002211306_bounded_deletion_preserve_paid_credit',
        '20260930175136_refund_request_notice_outbox', '20260930213049_account_lifecycle_mail_outbox',
        '20261002211015_server_managed_loyalty_terms', '20261003111631_simplify_loyalty_payment_terms',
        '20261003115914_readonly_loyalty_admission']) await install(n);
      if (process.env.FACTUAL_CLEANUP_INVENTORY_ONLY === '1') {
        for (const n of ['20261005134908_ninety_day_account_recovery',
          '20261001140307_mail_transactional_postal_split', '20260930193130_new_payment_service_control',
          '20261005152329_loyalty_action_consent', '20261005180901_voluntary_deletion_credit_surrender',
          '20261005181711_publish_approved_loyalty_policy']) await install(n);
        await exerciseFactualCleanupInventory({ db, run, check, cluster });
        return;
      }
      await exerciseNinetyDayRecovery({ db, run, check, cluster });
      if (process.env.CREDIT_SURRENDER_ONLY === '1') {
        await exerciseVoluntarySurrender({ db, run, check, cluster });
        if (process.env.FACTUAL_CLEANUP_INVENTORY === '1') {
          await exerciseFactualCleanupInventory({ db, run, check, cluster });
        }
      }
      return;
    }
    await exerciseLifecycle({ db, run, check });
    await exercisePopulatedRelations({ db, run, check });
    await exerciseBoundaries({ db, run, check, cluster });
    // Historical migration assertions above remain intact. Exercise the new
    // policy separately against the same catalog-matched, populated database.
    await db.query('revoke all on function public.request_account_deletion() from public,anon,authenticated,service_role;');
    await install('20260930213402_canonical_admin_onboarding');
    await install('20261001013709_owner_management');
    await check('paid-credit replacement preserves routine OIDs, owners and exact role grants', async () => {
      const replacedSignatures = [
        'private.require_account_cleanup_policy(text,text)', 'private.guard_account_cleanup_auth_delete()',
        'private.prune_account_cleanup_retention()', 'private.capture_topup_refund_spend()',
        'private.capture_topup_refund_provenance()', 'private.release_topup_refund(uuid)',
        'public.record_wallet_load_from_stripe(uuid,integer,text,text,text,text)',
      ];
      const grants = () => db.query(`select jsonb_agg(jsonb_build_array(p.oid,p.proowner,p.proacl)
        order by p.oid) from pg_proc p where p.oid in
        (${replacedSignatures.map(s => `'${s}'::regprocedure`).join(',')});`);
      const before = await grants();
      await install('20261002211306_bounded_deletion_preserve_paid_credit');
      assert.equal(await grants(), before);
    });
    await exercisePaidCreditPreservation({ db, run, check, cluster });
  } finally {
    clearTimeout(deadline);
    await cluster.close();
    await assert.rejects(access(cluster.root), { code: 'ENOENT' });
    t.diagnostic('CLEANUP VERIFIED: all psql sessions exited, PG stopped, owned cluster directory absent');
  }
});
