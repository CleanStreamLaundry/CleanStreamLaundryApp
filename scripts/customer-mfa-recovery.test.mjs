import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { disposableCluster, blocked } from './test-support/policy-admission-pg.mjs';

const read = (p) => readFile(new URL(`../${p}`, import.meta.url), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await migration('20260930202731_customer_mfa_recovery');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner=uid(1), admin=uid(2), customer=uid(3), sid=uid(11), asid=uid(12), csid=uid(13);
const factor=uid(21), afactor=uid(22), lost=uid(23), freshFactor=uid(24);
const quote = (v) => v === null ? 'null' : `'${String(v).replaceAll("'", "''")}'`;
const claims = (extra={}) => ({ sub:owner, session_id:sid, role:'authenticated', aal:'aal2',
  exp:Math.floor(Date.now()/1000)+3600, ...extra });
const context = (jwt=claims(),role='authenticated') =>
  `set local request.jwt.claims=${quote(JSON.stringify(jwt))}; set local request.jwt.claim.sub=''; set local role ${role};`;
const asUser = (sql,jwt,role) => `begin; ${context(jwt,role)} ${sql}; commit;`;
const rpc = (action='prepare',target=customer,reference='CASE-123',verified=true,id=null) =>
  `select public.customer_mfa_recovery_request(${quote(action)},${quote(target)},${quote(reference)},${verified === null ? 'null' : verified},${quote(id)})`;
const customerClaims = (extra={}) => claims({sub:customer,session_id:csid,aal:'aal1',...extra});

test('Owner verified customer recovery: durable fence, canonical reenrollment and safe retries', {timeout:180000}, async (t) => {
  const cluster=await disposableCluster(t,process.env.PG_BIN), db=await cluster.connect();
  const run=async (sql) => { const s=await cluster.connect(); try { return await s.query(sql); } finally { await s.close(); } };
  const call=(sql=rpc(),jwt,role) => run(asUser(sql,jwt,role));
  const failure=(code) => (e) => { assert.equal(e.code,code,e.message); return true; };
  const fixture=(await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length,2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance','20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution','20260929231120_serialize_wallet_financial_writes']) await db.query(await migration(n));
  await db.query(`grant execute on function public.is_admin_or_owner() to authenticated;
    create trigger handle_transaction after insert on public.transactions for each row execute function public.update_user_balance();`);
  for (const n of ['20260807195409_configure_dryer_time_options','20260922224735_cortina_price_array_selectors',
    '20260928132533_link_cortina_transaction_history']) await db.query(await migration(n));
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false, add column banned_until timestamptz,
    add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;`);
  for (const n of ['20260929223124_protect_profile_authority','20260929234955_loyalty_policy_acceptance']) await db.query(await migration(n));
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission','20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership','20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text, add column "Address" text, add column "Latitude" double precision, add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer, add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id text primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);`);
  for (const n of ['20260928135006_admin_portal_operations','20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting','20260930142406_admin_canonical_authorization',
    '20260930171558_human_wallet_spend_admission','20260930184955_wallet_read_admission']) await db.query(await migration(n));
  await db.query(`reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status) on auth.mfa_factors to postgres;
    grant select(created_at) on auth.mfa_factors to postgres with grant option;
    alter role postgres nosuperuser bypassrls;`);
  const definitions=() => db.query(`select jsonb_object_agg(oid::regprocedure::text,jsonb_build_array(pg_get_functiondef(oid),proacl))
    from pg_proc where pronamespace in ('public'::regnamespace,'private'::regnamespace) and prokind='f'
      and proname not in ('current_account_access','customer_mfa_recovery_request','guard_customer_recovery_role');`);
  const before=await definitions();
  await db.query(`set role postgres; ${candidate} reset role;`);
  const reset=() => db.query(`truncate auth.users cascade; truncate public.admin_audit_events;
    insert into auth.users(id,email_confirmed_at) values('${owner}',now()),('${admin}',now()),('${customer}',now());
    insert into public.profiles(id,roles,full_name) values('${owner}','Owner','Owner'),('${admin}','Admin','Admin'),('${customer}','User','Customer');
    insert into auth.sessions(id,user_id,aal,factor_id,created_at) values
      ('${sid}','${owner}','aal2','${factor}',now()-interval '1 minute'),
      ('${asid}','${admin}','aal2','${afactor}',now()-interval '1 minute'),
      ('${csid}','${customer}','aal1',null,now()-interval '1 hour');
    insert into auth.mfa_factors(id,user_id,factor_type,status,created_at) values
      ('${factor}','${owner}','totp','verified',now()-interval '1 day'),
      ('${afactor}','${admin}','totp','verified',now()-interval '1 day'),
      ('${lost}','${customer}','totp','verified',now()-interval '1 day');`);
  const fresh=(name,fn) => t.test(name,async () => { await reset(); await fn(); });
  const state=() => db.query(`select jsonb_build_object('fence',(select jsonb_agg(r) from private.customer_mfa_recovery r),
    'audit',(select jsonb_agg(a order by id) from public.admin_audit_events a),
    'factors',(select jsonb_agg(f order by id) from auth.mfa_factors f));`);
  const deny=async (sql=rpc(),jwt,code='PT403',role) => {
    const before=await state(); await assert.rejects(call(sql,jwt,role),failure(code)); assert.equal(await state(),before);
  };
  const newSession=() => db.query(`update auth.sessions set created_at=clock_timestamp(),aal='aal1',factor_id=null where id='${csid}';`);
  const removeOld=() => db.query(`delete from auth.mfa_factors where id='${lost}';`);
  const enroll=() => db.query(`insert into auth.mfa_factors(id,user_id,factor_type,status,created_at)
    values('${freshFactor}','${customer}','totp','verified',clock_timestamp());
    update auth.sessions set aal='aal2',factor_id='${freshFactor}' where id='${csid}';`);
  const admission=async (jwt=customerClaims()) => JSON.parse(await call('select public.get_admission_status()',jwt));
  await fresh('only canonical evaluator changes; staff/payment/refund functions retain exact definitions and ACLs',async () => {
    assert.equal(await definitions(),before);
  });
  await fresh('private fence has no client/service privileges; RPC authenticated only',async () => {
    for (const role of ['anon','authenticated','service_role','supabase_auth_admin']) {
      assert.equal(await db.query(`select has_table_privilege('${role}','private.customer_mfa_recovery','select,insert,update,delete');`),'f');
    }
    for (const role of ['anon','service_role']) assert.equal(await db.query(`select has_function_privilege('${role}',
      'public.customer_mfa_recovery_request(text,uuid,text,boolean,uuid)','execute');`),'f');
  });
  await fresh('Owner without customer Home terms inspects exact target without mutation',async () => {
    const before=await state(); const result=JSON.parse(await call(rpc('inspect')));
    assert.equal(result.state,'not_started'); assert.equal(result.recovery_id,null); assert.equal(await state(),before);
  });
  await fresh('Owner verified support case fences and audits atomically without Auth deletion',async () => {
    const result=JSON.parse(await call()); assert.equal(result.state,'removal_pending');
    assert.deepEqual(result.remaining_factor_ids,[lost]);
    assert.equal(await db.query('select count(*) from auth.mfa_factors;'),'3');
    const event=JSON.parse(await db.query(`select to_jsonb(a) from public.admin_audit_events a;`));
    assert.equal(event.actor_id,owner); assert.equal(event.operation,'verified_recovery_started');
    assert.equal(event.after_values.support_case,'CASE-123'); assert.equal(event.after_values.externally_verified,true);
    assert(!JSON.stringify(event).includes('fixture_secret'));
  });
  for (const [name,jwt] of [['Admin',claims({sub:admin,session_id:asid})],['customer',customerClaims()],
    ['Owner AAL1',claims({aal:'aal1'})],['spoofed metadata',claims({sub:admin,session_id:asid,user_metadata:{role:'Owner'}})]]) {
    await fresh(`${name} cannot initiate recovery`,() => deny(rpc(),jwt));
  }
  for (const target of [owner,admin,uid(999)]) await fresh(`reject privileged/self/missing target ${target}`,() => deny(rpc('prepare',target)));
  for (const [name,sql] of [
    ['old Owner session',`update auth.sessions set created_at=now()-interval '10 minutes' where id='${sid}'`],
    ['future Owner session',`update auth.sessions set created_at=now()+interval '1 minute' where id='${sid}'`],
    ['deleted Owner factor',`delete from auth.mfa_factors where id='${factor}'`],
    ['Owner factor binding mismatch',`update auth.sessions set factor_id='${lost}' where id='${sid}'`],
    ['unverified target',`update auth.users set email_confirmed_at=null where id='${customer}'`],
    ['banned target',`update auth.users set banned_until=now()+interval '1 hour' where id='${customer}'`],
    ['deleted target',`update auth.users set deleted_at=now() where id='${customer}'`],
    ['anonymous target',`update auth.users set is_anonymous=true where id='${customer}'`],
    ['pending deletion',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until) values('${customer}',now(),now()+interval '720 hours')`],
    ['unsupported factor',`update auth.mfa_factors set factor_type='phone' where id='${lost}'`],
    ['no lost verified factor',`update auth.mfa_factors set status='unverified' where id='${lost}'`],
  ]) await fresh(name,async () => { await db.query(sql); await deny(); });
  for (const [reference,verified] of [[null,true],['',true],[' bad ',true],['line\nbreak',true],['x'.repeat(121),true],['CASE-123',false],['CASE-123',null]]) {
    await fresh(`case proof ${JSON.stringify([reference,verified])} rejected`,() => deny(rpc('prepare',customer,reference,verified),undefined,'22023'));
  }
  await fresh('same case replay read-only, cutoff and snapshot unchanged',async () => {
    const first=JSON.parse(await call()); const before=await state();
    assert.deepEqual(JSON.parse(await call()),first); assert.equal(await state(),before);
  });
  await fresh('different case cannot replace pending operation',async () => {
    await call(); await deny(rpc('prepare',customer,'CASE-456'),undefined,'PT409');
  });
  await fresh('authorization requires exact recovery ID and current Owner',async () => {
    const r=JSON.parse(await call()); await deny(rpc('authorize',customer,null,false,uid(99)),undefined,'PT409');
    await deny(rpc('authorize',customer,null,false,r.recovery_id),claims({sub:admin,session_id:asid}));
    const result=JSON.parse(await call(rpc('authorize',customer,null,false,r.recovery_id)));
    assert.deepEqual(result.remaining_factor_ids,[lost]);
    assert.equal(await db.query(`select count(*) from public.admin_audit_events where operation='factor_removal_authorized';`),'1');
  });
  await fresh('old customer session is invalid even while its lost factor still verifies',async () => {
    await call(); await assert.rejects(admission(),failure('PT401'));
  });
  await fresh('fresh session cannot use a still-present old factor',async () => {
    await call(); await newSession();
    await db.query(`update auth.sessions set aal='aal2',factor_id='${lost}' where id='${csid}';`);
    const a=await admission(customerClaims({aal:'aal2'})); assert.equal(a.reason,'account_restricted'); assert.equal(a.next_step,'blocked');
  });
  await fresh('after removal password-only access requires enrollment, never Home',async () => {
    await call(); await removeOld(); await newSession(); assert.equal((await admission()).next_step,'enroll_totp');
  });
  await fresh('new verified TOTP still requires bound current AAL2',async () => {
    await call(); await removeOld(); await newSession(); await enroll();
    assert.equal((await admission()).next_step,'challenge_totp');
    await db.query(`update auth.sessions set factor_id=null where id='${csid}';`);
    assert.equal((await admission(customerClaims({aal:'aal2'}))).next_step,'challenge_totp');
  });
  await fresh('fresh new-factor AAL2 reaches existing terms gate; old session stays invalid',async () => {
    await call(); await removeOld(); await newSession(); await enroll();
    assert.equal((await admission(customerClaims({aal:'aal2'}))).next_step,'review_terms');
    await db.query(`update auth.sessions set created_at=now()-interval '1 day' where id='${csid}';`);
    await assert.rejects(admission(customerClaims({aal:'aal2'})),failure('PT401'));
  });
  await fresh('pre-cutoff concurrent factor cannot satisfy mandatory new enrollment',async () => {
    await call(); await removeOld(); await newSession(); await enroll();
    await db.query(`update auth.mfa_factors set created_at=now()-interval '1 day' where id='${freshFactor}';`);
    assert.equal((await admission(customerClaims({aal:'aal2'}))).next_step,'enroll_totp');
  });
  await fresh('removing new factor never restores password-only eligibility',async () => {
    await call(); await removeOld(); await newSession(); await enroll();
    await db.query(`delete from auth.mfa_factors where id='${freshFactor}';`);
    assert.equal((await admission()).next_step,'enroll_totp');
  });
  await fresh('lost response retry excludes new verified factor and keeps immutable audit',async () => {
    const r=JSON.parse(await call()); await removeOld(); await newSession(); await enroll();
    assert.deepEqual(JSON.parse(await call()).remaining_factor_ids,[]);
    assert.deepEqual(JSON.parse(await call(rpc('authorize',customer,null,false,r.recovery_id))).remaining_factor_ids,[]);
    assert.equal(await db.query(`select count(*) from auth.mfa_factors where id='${freshFactor}';`),'1');
    await assert.rejects(run(`update public.admin_audit_events set operation='tampered';`));
  });
  await fresh('new verified recovery case can advance cutoff only after previous old factors gone',async () => {
    const first=JSON.parse(await call()); await removeOld(); await newSession(); await enroll();
    const second=JSON.parse(await call(rpc('prepare',customer,'CASE-456')));
    assert.notEqual(first.recovery_id,second.recovery_id); assert.deepEqual(second.remaining_factor_ids,[freshFactor]);
    await deny(rpc('authorize',customer,null,false,first.recovery_id),undefined,'PT409');
  });
  await fresh('role promotion cannot race an outstanding removal; unrelated profile fields unchanged',async () => {
    await call(); await assert.rejects(run(`update public.profiles set roles='Admin' where id='${customer}';`),failure('PT409'));
    await db.query(`update public.profiles set full_name='New name' where id='${customer}';`);
    await removeOld(); await db.query(`update public.profiles set roles='Admin' where id='${customer}';`);
    await deny(rpc('inspect'));
  });
  await fresh('exact recovery cutoff equality cannot revive a session',async () => {
    await call(); await removeOld();
    await db.query(`update auth.sessions set created_at=(select started_at from private.customer_mfa_recovery where user_id='${customer}') where id='${csid}';`);
    await assert.rejects(admission(),failure('PT401'));
  });
  await fresh('audit insert failure rolls back durable fence with no Auth mutation',async () => {
    const original=await state();
    await assert.rejects(run(`begin; alter table public.admin_audit_events add constraint fixture_reject_recovery
      check(entity<>'customer_mfa_recovery'); ${context()} ${rpc()}; commit;`),failure('23514'));
    assert.equal(await state(),original);
  });
  await fresh('completed recovery does not bypass a later deletion request',async () => {
    await call(); await removeOld(); await newSession(); await enroll();
    await db.query(`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
      values('${customer}',now(),now()+interval '720 hours');`);
    const a=await admission(customerClaims({aal:'aal2'}));
    assert.equal(a.account_state,'pending_deletion'); assert.equal(a.account_access,'restricted');
  });
  await fresh('target promoted while prepare waits is rejected after lock wait',async () => {
    const holder=await cluster.connect(), waiting=await cluster.connect();
    try {
      await holder.query(`begin; update public.profiles set roles='Admin' where id='${customer}';`);
      const pending=waiting.query(asUser(rpc())); const rejected=assert.rejects(pending,failure('PT403'));
      await blocked(db,waiting,holder); await holder.query('commit;'); await rejected;
      assert.equal(await db.query('select count(*) from private.customer_mfa_recovery;'),'0');
    } finally { await holder.close(); await waiting.close(); }
  });
  await fresh('Owner factor removed during audit INSERT wait rolls back fence and audit',async () => {
    const holder=await cluster.connect(), waiting=await cluster.connect();
    try {
      await holder.query('begin; lock table public.admin_audit_events in share mode;');
      const pending=waiting.query(asUser(rpc())); const rejected=assert.rejects(pending,failure('PT403'));
      await blocked(db,waiting,holder); await db.query(`delete from auth.mfa_factors where id='${factor}';`);
      await holder.query('commit;'); await rejected;
      assert.equal(await db.query('select count(*) from private.customer_mfa_recovery;'),'0');
      assert.equal(await db.query('select count(*) from public.admin_audit_events;'),'0');
    } finally { await holder.close(); await waiting.close(); }
  });
});
