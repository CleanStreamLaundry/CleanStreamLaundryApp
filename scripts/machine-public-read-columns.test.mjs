import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.env.MACHINE_COLUMNS_APP_ROOT;
assert(root && isAbsolute(root), 'Set MACHINE_COLUMNS_APP_ROOT to the accepted read-only app');
const active = pathToFileURL(`${root}/`);
const { disposableCluster } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', active));
const read = (p) => readFile(new URL(p, active), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await readFile(new URL('../supabase/migrations/20261001095826_machine_public_read_columns.sql', import.meta.url), 'utf8');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner = uid(1), staff = uid(2), customer = uid(3);
const claims = (n = 1) => ({ sub: uid(n), session_id: uid(n + 10), role: 'authenticated',
  aal: n === 3 ? 'aal1' : 'aal2', exp: Math.floor(Date.now() / 1000) + 3600 });
const literal = (v) => `'${String(v).replaceAll("'", "''")}'`;
const table = 'public."Machines"';
const publicColumns = ['id', 'Name', 'Price', 'Runtime', 'Status', 'Location_ID', 'Machine_type',
  'Weight_kg', 'washer_size_rate_id', 'is_out_of_service', 'service_updated_at'];
const projection = publicColumns.map((c) => `"${c}"`).join(',');

test('machine inventory column privacy with actual canonical staff SQL', { timeout: 180000 }, async (t) => {
  const cluster = await disposableCluster(t, process.env.PG_BIN), db = await cluster.connect();
  const run = async (sql) => {
    const session = await cluster.connect();
    try { return await session.query(sql); } finally { await session.close(); }
  };
  const as = (sql, role = 'authenticated', jwt = claims(), setup = '') => run(`begin;
    ${setup} set local request.jwt.claims=${literal(JSON.stringify(jwt))};
    set local request.jwt.claim.sub=''; set local role ${role}; ${sql}; rollback;`);
  const denied = (sql, role, jwt, setup) => assert.rejects(as(sql, role, jwt, setup),
    (e) => { assert.equal(e.code, '42501', e.message); return true; });

  // Same accepted synthetic prerequisite chain as the focused membership suite.
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length, 2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance', '20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution', '20260929231120_serialize_wallet_financial_writes',
    '20260807195409_configure_dryer_time_options', '20260922224735_cortina_price_array_selectors',
    '20260928132533_link_cortina_transaction_history']) await db.query(await migration(n));
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false, add column banned_until timestamptz,
    add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;
    grant select on public."Location_to_Admin" to anon,authenticated;
    create policy legacy_membership_public_read on public."Location_to_Admin" for select to public using(true);`);
  for (const n of ['20260929223124_protect_profile_authority', '20260929234955_loyalty_policy_acceptance']) {
    await db.query(await migration(n));
  }
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission', '20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership', '20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text, add column "Address" text, add column "Latitude" double precision, add column "Longitude" double precision;
    alter table ${table} add column "Runtime" integer, add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id bigint primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);
    alter table ${table} enable row level security;
    alter table public."Locations" enable row level security;
    grant select on ${table},public."Locations" to anon,authenticated;
    create policy legacy_machine_public_read on ${table} for select to public using(true);
    create policy legacy_machine_block_update on ${table} as restrictive for update to public using(false) with check(false);
    create policy legacy_location_public_read on public."Locations" for select to public using(true);`);
  for (const n of ['20260928135006_admin_portal_operations', '20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting', '20260930142406_admin_canonical_authorization',
    '20260930202731_customer_mfa_recovery', '20260930213402_canonical_admin_onboarding']) {
    await db.query(await migration(n));
  }
  await db.query(`revoke all on function public.request_account_deletion() from public,anon,authenticated,service_role;
    revoke all on function public.is_admin_or_owner() from public,anon;
    grant execute on function public.is_admin_or_owner() to authenticated;
    -- Match the observed rDxtm shape; this read-only batch must not alter it.
    grant truncate,references,trigger,maintain on ${table} to anon,authenticated;
    reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status,created_at) on auth.mfa_factors to postgres;
    alter role postgres nosuperuser bypassrls;
    insert into auth.users(id,email_confirmed_at) values('${owner}',now()),('${staff}',now()),('${customer}',now());
    insert into public.profiles(id,roles) values('${owner}','Owner'),('${staff}','Admin'),('${customer}','User');
    insert into auth.mfa_factors(id,user_id,factor_type,status) values
      ('${uid(21)}','${owner}','totp','verified'),('${uid(22)}','${staff}','totp','verified');
    insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
      ('${uid(11)}','${owner}','aal2',now()-interval '1 hour','${uid(21)}'),
      ('${uid(12)}','${staff}','aal2',now()-interval '1 hour','${uid(22)}'),
      ('${uid(13)}','${customer}','aal1',now()-interval '1 hour',null);
    insert into public."Locations"(id,"Name","Address") values(100,'North','Public address'),(200,'South','Public address');
    insert into public."Location_to_Admin"(user_id,location_id) values('${owner}',100),('${staff}',100);
    insert into ${table}(id,"Location_ID","Name","Machine_type","Price","Runtime","Status","Weight_kg",
      service_reason,service_updated_by) values(100,100,'Dryer','Dryer',0.25,5,'idle',10,'Synthetic staff note','${owner}');`);

  const permissions = () => db.query(`select jsonb_build_object('table',
    (select relacl from pg_class where oid='${table}'::regclass),
    'columns',(select jsonb_agg(jsonb_build_array(attname,attacl) order by attnum)
      from pg_attribute where attrelid='${table}'::regclass and attnum>0 and not attisdropped));`);
  const invariant = () => db.query(`select jsonb_build_object(
    'machines',(select jsonb_agg(to_jsonb(m) order by id) from ${table} m),
    'profiles',(select jsonb_agg(to_jsonb(p) order by id) from public.profiles p),
    'audit',(select jsonb_agg(to_jsonb(a) order by id) from public.admin_audit_events a),
    'functions',(select jsonb_agg(jsonb_build_array(p.oid,pg_get_functiondef(p.oid),p.proacl,p.proowner) order by p.oid)
      from pg_proc p where p.pronamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace) and p.prokind='f'),
    'policies',(select jsonb_agg(to_jsonb(p) order by oid) from pg_policy p),
    'tables',(select jsonb_agg(jsonb_build_array(c.oid,c.relowner,c.relrowsecurity,c.relforcerowsecurity,
      case when c.oid<>'${table}'::regclass then c.relacl end) order by c.oid)
      from pg_class c where c.relnamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace)),
    'other_privileges',(select jsonb_agg(jsonb_build_array(r,p,has_table_privilege(r,'${table}',p)) order by r,p)
      from unnest(array['anon','authenticated','service_role']) r cross join unnest(array[
        'INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p),
    'service_columns',(select jsonb_agg(jsonb_build_array(attname,has_column_privilege('service_role',attrelid,attnum,'SELECT')) order by attnum)
      from pg_attribute where attrelid='${table}'::regclass and attnum>0 and not attisdropped));`);
  const originalPermissions = await permissions(), originalInvariant = await invariant();
  const body = candidate.replace(/^begin;$/m, '').replace(/^commit;$/m, '');
  const failedInstall = (setup) => assert.rejects(run(`begin; ${setup} set local role postgres; ${body} commit;`),
    (e) => { assert.equal(e.code, '42501', e.message); return true; });
  await t.test('baseline matches broad private-column reads despite denied financial inventory writes', async () => {
    for (const role of ['anon', 'authenticated']) {
      assert.equal(await as(`select service_reason from ${table}`, role), 'Synthetic staff note');
      assert.equal(await as(`select service_updated_by from ${table}`, role), owner);
    }
    assert.equal(await db.query("select not rolsuper and rolbypassrls from pg_roles where rolname='postgres';"), 't');
  });
  for (const [name, setup] of [
    ['inherited table grant', `create role fixture_parent; grant select on ${table} to fixture_parent;
      grant fixture_parent to anon with inherit true,set false;`],
    ['inherited private column', `create role fixture_parent; grant select(service_reason) on ${table} to fixture_parent;
      grant fixture_parent to authenticated with inherit true,set false;`],
    ['SET-only parent', `create role fixture_parent; grant select on ${table} to fixture_parent;
      grant fixture_parent to authenticated with inherit false,set true;`],
  ]) await t.test(`${name} fails atomically without revoking another role`, async () => {
    await failedInstall(setup);
    assert.equal(await permissions(), originalPermissions);
    assert.equal(await db.query("select count(*) from pg_roles where rolname='fixture_parent';"), '0');
  });
  await t.test('unexpected bypass role fails atomically', async () => {
    await failedInstall('alter role anon bypassrls;');
    assert.equal(await permissions(), originalPermissions);
    assert.equal(await db.query("select rolbypassrls from pg_roles where rolname='anon';"), 'f');
  });
  await t.test('missing reviewed private column fails before grant changes', async () => {
    await assert.rejects(run(`begin; set local role postgres;
      alter table ${table} rename column service_reason to fixture_missing; ${body} commit;`),
      (e) => { assert.equal(e.code, '55000'); return true; });
    assert.equal(await permissions(), originalPermissions);
  });
  await t.test('PUBLIC and explicit private-column grants are removed with no other schema or row changes', async () => {
    await db.query(`set role postgres; grant select on ${table} to public;
      grant select(service_reason,service_updated_by) on ${table} to public,anon,authenticated;
      ${candidate} reset role;`);
    assert.equal(await invariant(), originalInvariant);
    for (const role of ['anon', 'authenticated']) {
      assert.equal(await db.query(`select has_table_privilege('${role}','${table}','SELECT');`), 'f');
      const allowed = JSON.parse(await db.query(`select jsonb_agg(attname order by attname)
        from pg_attribute where attrelid='${table}'::regclass and attnum>0 and not attisdropped
          and has_column_privilege('${role}',attrelid,attnum,'SELECT');`));
      assert.deepEqual(allowed, [...publicColumns].sort());
    }
  });
  for (const role of ['anon', 'authenticated']) {
    await t.test(`${role} retains the explicit eleven-column projection and existing counts/price`, async () => {
      const rows = JSON.parse(await as(`select jsonb_agg(to_jsonb(x)) from (select ${projection} from ${table}) x`, role));
      assert.deepEqual(Object.keys(rows[0]).sort(), [...publicColumns].sort());
      assert.equal(rows[0].Name, 'Dryer');
      assert.equal(rows[0].Price, 0.25);
      assert.equal(await as(`select count(id) from ${table} where "Location_ID"=100 and "Machine_type"='Dryer' and "Status"='idle'`, role), '1');
    });
    for (const [name, sql] of [
      ['private note', `select service_reason from ${table}`],
      ['staff UUID', `select service_updated_by from ${table}`],
      ['wildcard', `select * from ${table}`],
      ['whole-row JSON', `select to_jsonb(m) from ${table} m`],
      ['private filter', `select id from ${table} where service_reason is not null`],
    ]) await t.test(`${role} cannot read ${name} through direct table access`, async () => { await denied(sql, role); });
  }
  await t.test('pending customer keeps public metadata but cannot gain staff notes', async () => {
    const setup = `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
      values('${customer}',now(),now()+interval '720 hours');`;
    assert.equal(await as(`select "Name" from ${table}`, 'authenticated', claims(3), setup), 'Dryer');
    await denied(`select service_reason from ${table}`, 'authenticated', claims(3), setup);
  });
  await t.test('canonical Owner/Admin staff RPC retains private note actor and nested configuration', async () => {
    for (const n of [1, 2]) {
      const rows = JSON.parse(await as("select public.admin_portal_request('machines','{\"locationId\":100}')", 'authenticated', claims(n)));
      assert.equal(rows[0].service_reason, 'Synthetic staff note');
      assert.equal(rows[0].service_updated_by, owner);
      assert.equal(rows[0].cortina_machine_config.machine_id, 100);
    }
    await assert.rejects(as("select public.admin_portal_request('machines','{\"locationId\":100}')", 'authenticated', claims(),
      `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
        values('${owner}',now(),now()+interval '720 hours');`), (e) => { assert.equal(e.code, 'PT403'); return true; });
  });
  await t.test('service and canonical definer updates preserve existing private fields and audit behavior', async () => {
    assert.equal(await as(`update ${table} set service_reason='Service changed' where id=100;
      select service_reason from ${table}`, 'service_role', {}), 'Service changed');
    const machine = JSON.parse(await as("select public.admin_portal_request('machines','{\"locationId\":100}')"))[0];
    const payload = { id: 100, outOfService: true, reason: 'Staff changed', expectedUpdatedAt: machine.service_updated_at };
    assert.deepEqual(JSON.parse(await as(`select public.admin_portal_request('setAvailability',${literal(JSON.stringify(payload))})`)), { success: true });
    assert.equal(await invariant(), originalInvariant);
  });
  await t.test('deletion hold and client INSERT UPDATE DELETE grants remain unchanged', async () => {
    assert.equal(await db.query(`select bool_and(not has_function_privilege(r,'public.request_account_deletion()','EXECUTE'))
      from unnest(array['anon','authenticated','service_role']) r;`), 't');
    assert.equal(await invariant(), originalInvariant);
  });
});
