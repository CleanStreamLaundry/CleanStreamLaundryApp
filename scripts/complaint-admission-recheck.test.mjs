import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { disposableCluster, blocked } from './test-support/policy-admission-pg.mjs';

const read = (p) => readFile(new URL(`../${p}`, import.meta.url), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await migration('20260930190143_complaint_admission_recheck');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner = uid(1), admin = uid(2), customer = uid(3), wallet = uid(4);
const sid = uid(11), asid = uid(12), factor = uid(21), afactor = uid(22);
const signature = 'public.record_deleted_account_complaint(uuid,text,text)';
const quote = (v) => v === null ? 'null' : `'${String(v).replaceAll("'", "''")}'`;
const claims = (extra = {}) => ({ sub:owner, session_id:sid, role:'authenticated',
  aal:'aal2', exp:Math.floor(Date.now()/1000)+3600, ...extra });
const context = (jwt = claims(), role = 'authenticated') =>
  `set local request.jwt.claims=${quote(JSON.stringify(jwt))}; set local request.jwt.claim.sub=''; set local role ${role};`;
const asUser = (sql, jwt, role) => `begin; ${context(jwt,role)} ${sql}; commit;`;
const complaint = (note = 'Original complaint', resolution = 'denied', target = wallet) =>
  `select public.record_deleted_account_complaint(${quote(target)},${quote(note)},${quote(resolution)})`;

test('global complaint records preserve staff policy and recheck authority after INSERT waits', {timeout:180000}, async (t) => {
  const cluster = await disposableCluster(t,process.env.PG_BIN), db = await cluster.connect();
  const run = async (sql) => {
    const s = await cluster.connect();
    try { return await s.query(sql); } finally { await s.close(); }
  };
  const call = (sql = complaint(), jwt, role) => run(asUser(sql,jwt,role));
  const failure = (code) => (e) => { assert.equal(e.code,code,e.message); return true; };
  const error = (sql,code) => assert.rejects(run(sql),failure(code));
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length,2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance','20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution','20260929231120_serialize_wallet_financial_writes']) {
    await db.query(await migration(n));
  }
  await db.query(`grant execute on function public.is_admin_or_owner() to authenticated;
    create trigger handle_transaction after insert on public.transactions
      for each row execute function public.update_user_balance();`);
  for (const n of ['20260807195409_configure_dryer_time_options',
    '20260922224735_cortina_price_array_selectors','20260928132533_link_cortina_transaction_history']) {
    await db.query(await migration(n));
  }
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false, add column banned_until timestamptz,
    add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;`);
  for (const n of ['20260929223124_protect_profile_authority','20260929234955_loyalty_policy_acceptance']) {
    await db.query(await migration(n));
  }
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission','20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership','20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text, add column "Address" text, add column "Latitude" double precision,
    add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer, add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id text primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);`);
  for (const n of ['20260928135006_admin_portal_operations','20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting','20260930142406_admin_canonical_authorization',
    '20260930171558_human_wallet_spend_admission','20260930184955_wallet_read_admission']) {
    await db.query(await migration(n));
  }
  await db.query(`reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status) on auth.mfa_factors to postgres;
    alter role postgres nosuperuser bypassrls;`);
  const metadata = () => db.query(`select jsonb_build_array(oid,proowner,proacl,prosecdef,provolatile,
    pg_get_function_arguments(oid),pg_get_function_result(oid)) from pg_proc where oid='${signature}'::regprocedure;`);
  const otherFunctions = () => db.query(`select jsonb_object_agg(oid::regprocedure::text,
    jsonb_build_array(pg_get_functiondef(oid),proacl,proowner)) from pg_proc
    where pronamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace)
      and prokind='f' and oid<>'${signature}'::regprocedure;`);
  const policies = () => db.query('select jsonb_agg(to_jsonb(p) order by oid) from pg_policy p;');
  const rows = () => db.query('select jsonb_agg(to_jsonb(c) order by id) from public.deleted_account_complaints c;');
  const money = () => db.query(`select jsonb_build_object(
    'wallet',(select jsonb_agg(to_jsonb(w) order by id) from public.wallet_accounts w),
    'loads',(select jsonb_agg(to_jsonb(w) order by id) from public.wallet_loads w),
    'ledger',(select jsonb_agg(to_jsonb(w) order by id) from public.wallet_ledger_entries w),
    'redemptions',(select jsonb_agg(to_jsonb(w) order by id) from public.wallet_redemptions w),
    'cache',(select jsonb_agg(jsonb_build_array(id,balance,reward_tracker) order by id) from public.profiles));`);
  const reset = () => db.query(`truncate auth.users cascade;
    insert into auth.users(id,email_confirmed_at) values('${owner}',now()),('${admin}',now()),('${customer}',now());
    insert into public.profiles(id,roles) values('${owner}','Owner'),('${admin}','Admin'),('${customer}','User');
    insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
      ('${sid}','${owner}','aal2',now()-interval '1 hour','${factor}'),
      ('${asid}','${admin}','aal2',now()-interval '1 hour','${afactor}'),
      ('${uid(13)}','${customer}','aal1',now()-interval '1 hour',null);
    insert into auth.mfa_factors(id,user_id,factor_type,status) values
      ('${factor}','${owner}','totp','verified'),('${afactor}','${admin}','totp','verified');
    insert into public.wallet_accounts(id,user_id) values('${wallet}','${customer}');
    insert into public.wallet_ledger_entries(wallet_account_id,entry_type,amount_cents,paid_amount_cents)
      values('${wallet}','legacy_balance',1000,1000);
    insert into public.deleted_account_complaints(wallet_account_id,complaint_note,resolution,created_by)
      values('${wallet}','Preserved historical note','denied','${admin}');`);
  const fresh = (name,fn) => t.test(name,async () => { await reset(); await fn(); });
  const unchangedFailure = async (sql,code) => {
    const before = await rows(), financial = await money();
    await error(sql,code); assert.equal(await rows(),before); assert.equal(await money(),financial);
  };
  await reset();
  const originalMetadata = await metadata(), originalFunctions = await otherFunctions();
  const originalPolicies = await policies(), originalRows = await rows(), originalMoney = await money();
  await t.test('missing staff helper aborts without replacing the complaint function',async () => {
    const body = candidate.replace(/^begin;$/m,'').replace(/^commit;$/m,'');
    await error(`begin; set local role postgres;
      alter function private.portal_staff_context() rename to fixture_missing_staff; ${body} commit;`,'55000');
    assert.equal(await metadata(),originalMetadata); assert.equal(await otherFunctions(),originalFunctions);
  });
  await db.query(`set role postgres; ${candidate} reset role;`);
  await t.test('one body changes; existing signature defaults ACLs policies history and money stay intact',async () => {
    assert.equal(await metadata(),originalMetadata); assert.equal(await otherFunctions(),originalFunctions);
    assert.equal(await policies(),originalPolicies); assert.equal(await rows(),originalRows);
    assert.equal(await money(),originalMoney);
    assert.equal(await db.query(`select proconfig=array['search_path=""'] from pg_proc where oid='${signature}'::regprocedure;`),'t');
    assert.equal(await db.query(`select not rolsuper and rolbypassrls from pg_roles where rolname='postgres';`),'t');
  });
  for (const [name,who,session] of [['Owner',owner,sid],['Admin',admin,asid]]) {
    for (const status of ['active','locked','deleted']) await fresh(`${name} records ${status} wallet complaint without location or customer terms`,async () => {
      await db.query(`update public.wallet_accounts set status='${status}' where id='${wallet}';`);
      const jwt = claims({sub:who,session_id:session});
      const admission = JSON.parse(await call('select public.get_admission_status()',jwt));
      assert.equal(admission.next_step,'review_terms');
      assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${who}';`),'0');
      const before = await money(), id = await call(complaint('  Original untrimmed note  '),jwt);
      assert.deepEqual(JSON.parse(await db.query(`select jsonb_build_array(wallet_account_id,complaint_note,resolution,created_by)
        from public.deleted_account_complaints where id=${id};`)),[wallet,'  Original untrimmed note  ','denied',who]);
      assert.equal(await money(),before);
      assert.equal(await db.query(`select count(*) from public.deleted_account_complaints where complaint_note='Preserved historical note';`),'1');
    });
  }
  for (const resolution of ['denied','legal_cash_redemption','other_required_remedy']) {
    await fresh(`existing ${resolution} label records metadata only`,async () => {
      const before = await money(), id = await call(complaint('Original complaint',resolution));
      assert.equal(await db.query(`select resolution from public.deleted_account_complaints where id=${id};`),resolution);
      assert.equal(await money(),before);
    });
  }
  await fresh('default resolution and distinct repeated records remain the original contract',async () => {
    const sql = `select public.record_deleted_account_complaint('${wallet}','Repeated note')`;
    const first = await call(sql), second = await call(sql); assert.notEqual(first,second);
    assert.equal(await db.query(`select count(*) from public.deleted_account_complaints
      where id in(${first},${second}) and resolution='denied' and created_by='${owner}';`),'2');
  });
  await fresh('historical wallet without user linkage remains recordable',async () => {
    await db.query(`update public.wallet_accounts set user_id=null,status='deleted' where id='${wallet}';`);
    const before = await money(); await call(); assert.equal(await money(),before);
  });
  for (const [note,resolution,target,code] of [
    [null,'denied',wallet,'P0001'],['   ','denied',wallet,'P0001'],
    ['note','unsupported',wallet,'23514'],['note',null,wallet,'23502'],
    ['note','denied',uid(999),'23503'],['note','denied',null,'23502'],
  ]) await fresh(`original note/resolution/FK constraints ${JSON.stringify([note,resolution,target])}`,async () => {
    await unchangedFailure(asUser(complaint(note,resolution,target)),code);
  });
  const changes = [
    ['session revocation',`delete from auth.sessions where id='${sid}'`,'PT401'],
    ['session expiration',`update auth.sessions set not_after=now()-interval '1 second' where id='${sid}'`,'PT401'],
    ['email unverified',`update auth.users set email_confirmed_at=null where id='${owner}'`,'PT403'],
    ['account banned',`update auth.users set banned_until=now()+interval '1 day' where id='${owner}'`,'PT403'],
    ['Auth deleted',`update auth.users set deleted_at=now() where id='${owner}'`,'PT403'],
    ['factor removed',`delete from auth.mfa_factors where id='${factor}'`,'PT403'],
    ['session downgraded',`update auth.sessions set aal='aal1' where id='${sid}'`,'PT403'],
    ['role demoted',`update public.profiles set roles='User' where id='${owner}'`,'PT403'],
    ['pending deletion',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
      values('${owner}',now(),now()+interval '30 days')`,'PT403'],
  ];
  for (const [name,change,code] of changes) await fresh(`precheck denies ${name} without insert`,async () => {
    await db.query(change); await unchangedFailure(asUser(complaint()),code);
  });
  await fresh('customer identity cannot create a global staff record',async () => {
    await unchangedFailure(asUser(complaint(),claims({sub:customer,session_id:uid(13),aal:'aal1'})),'PT403');
  });
  await fresh('anonymous caller and service identity cannot create attributed records',async () => {
    await unchangedFailure(asUser(complaint(),{},'anon'),'42501');
    const allowed = await db.query(`select has_function_privilege('service_role','${signature}','execute');`);
    await unchangedFailure(asUser(complaint(),{role:'service_role'},'service_role'),allowed==='t'?'PT401':'42501');
  });
  await fresh('three global money/status RPCs remain revoked',async () => {
    for (const fn of ['admin_adjust_wallet(uuid,integer,integer,integer,text)',
      'admin_set_wallet_status(uuid,text,text)','admin_record_legal_cash_redemption(uuid,integer,text,text)']) {
      for (const role of ['anon','authenticated','service_role']) {
        assert.equal(await db.query(`select has_function_privilege('${role}','public.${fn}','execute');`),'f');
      }
    }
  });
  for (const [name,change,code] of changes) await fresh(`wallet FK wait rolls back complaint after ${name}`,async () => {
    const holder = await cluster.connect(), waiter = await cluster.connect(), before = await rows();
    try {
      await holder.query(`begin; select 1 from public.wallet_accounts where id='${wallet}' for update;`);
      const rejected = assert.rejects(waiter.query(asUser(complaint())),failure(code));
      await blocked(db,waiter,holder); await db.query(change);
      const financial = await money(); await holder.query('commit;'); await rejected;
      assert.equal(await rows(),before); assert.equal(await money(),financial);
    } finally { await holder.close(); await waiter.close(); }
  });
  for (const [name,change,code] of changes.filter(([name]) =>
    ['session revocation','factor removed','pending deletion'].includes(name))) {
    await fresh(`AFTER INSERT trigger wait rolls back written complaint after ${name}`,async () => {
      await db.query(`create function public.fixture_complaint_wait() returns trigger language plpgsql as $$
        begin perform pg_advisory_xact_lock(73139); return null; end; $$;
        create trigger zz_fixture_complaint_wait after insert on public.deleted_account_complaints
          for each row execute function public.fixture_complaint_wait();`);
      const holder = await cluster.connect(), waiter = await cluster.connect(), before = await rows();
      try {
        await holder.query('begin; select pg_advisory_xact_lock(73139);');
        const rejected = assert.rejects(waiter.query(asUser(complaint())),failure(code));
        await blocked(db,waiter,holder); await db.query(change);
        const financial = await money(); await holder.query('commit;'); await rejected;
        assert.equal(await rows(),before); assert.equal(await money(),financial);
      } finally {
        await holder.close(); await waiter.close();
        await db.query(`drop trigger zz_fixture_complaint_wait on public.deleted_account_complaints;
          drop function public.fixture_complaint_wait();`);
      }
    });
  }
  await fresh('postcheck requires captured actor even if a trusted trigger switches to another eligible staff identity',async () => {
    await db.query(`create function public.fixture_complaint_actor() returns trigger language plpgsql as $$
      begin perform set_config('request.jwt.claims',${quote(JSON.stringify(claims({sub:admin,session_id:asid})))},true);
      return null; end; $$;
      create trigger zz_fixture_complaint_actor after insert on public.deleted_account_complaints
        for each row execute function public.fixture_complaint_actor();`);
    try { await unchangedFailure(asUser(complaint()),'PT403'); }
    finally {
      await db.query(`drop trigger zz_fixture_complaint_actor on public.deleted_account_complaints;
        drop function public.fixture_complaint_actor();`);
    }
  });
});
