import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

const sourceRoot = process.env.ADMIN_ONBOARDING_APP_ROOT;
assert(!sourceRoot || isAbsolute(sourceRoot), 'ADMIN_ONBOARDING_APP_ROOT must be an absolute read-only prerequisite root');
const active = sourceRoot ? pathToFileURL(`${sourceRoot}/`) : new URL('../', import.meta.url);
const { disposableCluster, blocked } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', active));
const read = (path) => readFile(new URL(path, active), 'utf8');
const migration = (name) => read(`supabase/migrations/${name}.sql`);
const candidate = await readFile(new URL('../supabase/migrations/20260930213402_canonical_admin_onboarding.sql', import.meta.url), 'utf8');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner=uid(1), admin=uid(2), customer=uid(3), other=uid(4), invited=uid(5);
const sid=uid(11), asid=uid(12), csid=uid(13), factor=uid(21), afactor=uid(22);
const quote = (v) => v === null ? 'null' : `'${String(v).replaceAll("'", "''")}'`;
const claims = (extra={}) => ({sub:owner,session_id:sid,role:'authenticated',aal:'aal2',exp:Math.floor(Date.now()/1000)+3600,...extra});
const context = (jwt=claims(),role='authenticated') => `set local request.jwt.claims=${quote(JSON.stringify(jwt))};
  set local request.jwt.claim.sub=''; set local role ${role};`;
const rpc = (action='invite', email='customer@example.invalid', ids=[100], target=null, request=null) =>
  `select public.admin_team_onboarding(${quote(action)},${quote(email)},${ids===null?'null':`array[${ids.map(n=>n===null?'null':n).join(',')}]::bigint[]`},${quote(target)},${quote(request)})`;

test('canonical Owner team onboarding, Auth boundary and existing audit/membership coexistence', {timeout:180000}, async (t) => {
  const cluster=await disposableCluster(t,process.env.PG_BIN), db=await cluster.connect();
  const run=async(sql)=>{const s=await cluster.connect();try{return await s.query(sql);}finally{await s.close();}};
  const call=(sql=rpc(),jwt,role)=>run(`begin; ${context(jwt,role)} ${sql}; commit;`);
  const json=(sql=rpc(),jwt,role)=>call(sql,jwt,role).then(JSON.parse);
  const reject=(sql,jwt,code='PT403',role)=>assert.rejects(call(sql,jwt,role),(e)=>{assert.equal(e.code,code,e.message);return true;});
  const fixture=(await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  await db.query('set client_min_messages=warning;create role postgres superuser;set role postgres;');
  await db.query(fixture[0]);
  for(const name of ['20260526010000_wallet_ledger_compliance','20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution','20260929231120_serialize_wallet_financial_writes']) await db.query(await migration(name));
  await db.query(`grant execute on function public.is_admin_or_owner() to authenticated;
    create trigger handle_transaction after insert on public.transactions for each row execute function public.update_user_balance();`);
  for(const name of ['20260807195409_configure_dryer_time_options','20260922224735_cortina_price_array_selectors',
    '20260928132533_link_cortina_transaction_history']) await db.query(await migration(name));
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,add column is_anonymous boolean default false,
    add column banned_until timestamptz,add column deleted_at timestamptz,add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}',add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" add column id bigint generated by default as identity primary key,
      add foreign key(user_id) references public.profiles(id) on update cascade on delete cascade,
      add foreign key(location_id) references public."Locations"(id);
    alter table public."Location_to_Admin" enable row level security;`);
  for(const name of ['20260929223124_protect_profile_authority','20260929234955_loyalty_policy_acceptance']) await db.query(await migration(name));
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for(const name of ['20260930005456_account_admission','20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership','20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(name));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text,add column "Address" text,add column "Latitude" double precision,add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer,add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id text primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);`);
  for(const name of ['20260928135006_admin_portal_operations','20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting','20260930142406_admin_canonical_authorization',
    '20260930202731_customer_mfa_recovery']) await db.query(await migration(name));
  const definitions=()=>db.query(`select jsonb_object_agg(oid::regprocedure::text,jsonb_build_array(pg_get_functiondef(oid),proacl))
    from pg_proc where pronamespace in('public'::regnamespace,'private'::regnamespace) and prokind='f'
    and proname not in('admin_team_onboarding','admin_team_invitation_delivered');`);
  const baseline=await definitions();
  await db.query(candidate);
  const reset=()=>db.query(`truncate auth.users cascade;truncate public.admin_audit_events;
    insert into auth.users(id,email,email_confirmed_at) values('${owner}','owner@example.invalid',now()),
      ('${admin}','admin@example.invalid',now()),('${customer}','customer@example.invalid',now()),('${other}','other@example.invalid',now());
    insert into public.profiles(id,email,roles,full_name) values('${owner}','owner@example.invalid','Owner','Owner'),
      ('${admin}','admin@example.invalid','Admin','Admin'),('${customer}','customer@example.invalid','User','Customer'),
      ('${other}','other@example.invalid','Owner','Other Owner');
    insert into auth.sessions(id,user_id,aal,factor_id,created_at) values('${sid}','${owner}','aal2','${factor}',now()),
      ('${asid}','${admin}','aal2','${afactor}',now()),('${csid}','${customer}','aal1',null,now());
    insert into auth.mfa_factors(id,user_id,factor_type,status,created_at) values('${factor}','${owner}','totp','verified',now()-interval '1 day'),
      ('${afactor}','${admin}','totp','verified',now()-interval '1 day');
    insert into public."Locations"(id,"Name") values(100,'North'),(200,'South') on conflict do nothing;
    delete from public."Location_to_Admin";
    insert into public."Location_to_Admin"(user_id,location_id) values('${owner}',100),('${admin}',100);`);
  const fresh=(name,fn)=>t.test(name,async()=>{await reset();await fn();});
  const role=()=>db.query(`select roles from public.profiles where id='${customer}';`);
  const complete=(r,target=customer)=>rpc('complete',null,null,target,r.request_id);
  const authorize=(r)=>rpc('authorize',null,null,null,r.request_id);
  const delivered=(r,target=customer)=>`select public.admin_team_invitation_delivered(${quote(r.request_id)},${quote(target)})`;
  const auditCount=()=>db.query("select count(*) from public.admin_audit_events where entity='team_onboarding';");

  await fresh('existing definitions, global revokes and bootstrap remain unchanged',async()=>{
    assert.equal(await definitions(),baseline);
    for(const name of ['admin_portal_assign_member(uuid,uuid,bigint[])','admin_portal_bootstrap_owner(uuid,bigint[])']) {
      assert.equal(await db.query(`select bool_and(not has_function_privilege(r,'public.${name}','execute'))
        from unnest(array['anon','authenticated','service_role']) r;`),'t');
    }
  });
  await fresh('human RPC and service delivery have disjoint effective grants',async()=>{
    for(const r of ['anon','service_role','supabase_auth_admin']) await reject(rpc(),undefined,'42501',r);
    for(const r of ['anon','authenticated','supabase_auth_admin']) await reject(delivered({request_id:'1'}),undefined,'42501',r);
    assert.equal(await db.query(`select bool_and(prosecdef and proconfig=array['search_path=""']::text[]) from pg_proc
      where proname in('admin_team_onboarding','admin_team_invitation_delivered');`),'t');
  });
  await fresh('prepare is audited but grants nothing; exact receipt completes atomically without Home terms',async()=>{
    assert.equal((await json('select public.get_admission_status()')).next_step,'review_terms');
    const r=await json();assert.equal(r.actor_id,owner);assert.equal(r.target_user_id,customer);
    assert.equal(r.email_action,'recovery');assert.deepEqual(r.location_ids,[100]);assert.equal(typeof r.request_id,'string');
    assert.equal(await role(),'User');assert.equal(await auditCount(),'1');
    assert.deepEqual(await json(authorize(r)),r);
    assert.equal((await json(complete(r))).target_user_id,customer);
    assert.equal(await role(),'Admin');assert.equal(await auditCount(),'2');
    assert.equal(await db.query(`select delivery_status from public.admin_invitations where user_id='${customer}'`),'pending');
    await call(delivered(r),{},'service_role');
    assert.equal(await db.query(`select delivery_status from public.admin_invitations where user_id='${customer}'`),'sent');
    assert.equal(await auditCount(),'3');
  });
  await fresh('new Auth identity can complete only its normalized authorized email; SQL never creates Auth users',async()=>{
    const r=await json(rpc('invite','NEW@example.invalid',[100,100]));
    assert.equal(r.email,'new@example.invalid');assert.equal(r.target_user_id,null);assert.equal(r.email_action,'invite');
    assert.equal(await db.query(`select count(*) from auth.users where id='${invited}'`),'0');
    await db.query(`insert into auth.users(id,email) values('${invited}','new@example.invalid');`);
    assert.equal((await json(complete(r,invited))).target_user_id,invited);
    assert.equal(await db.query(`select roles from public.profiles where id='${invited}'`),'Admin');
    assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${invited}'`),'1');
  });
  await fresh('resend requires an existing Admin membership and never expands locations',async()=>{
    const r=await json(rpc('resend',null,[100],admin));
    assert.equal(r.target_user_id,admin);
    await json(complete(r,admin));await call(delivered(r,admin),{},'service_role');
    assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${admin}'`),'1');
    await reject(rpc('resend',null,[100],customer),undefined,'PT409');
    await reject(rpc('resend',null,[200],admin));
  });
  await fresh('completed receipt/delivery replay is read-only and never restores removed membership',async()=>{
    const r=await json();await json(complete(r));await call(delivered(r),{},'service_role');
    const before=await db.query('select jsonb_agg(a order by id) from public.admin_audit_events a;');
    await json(complete(r));await call(delivered(r),{},'service_role');
    assert.equal(await db.query('select jsonb_agg(a order by id) from public.admin_audit_events a;'),before);
    await db.query(`delete from public."Location_to_Admin" where user_id='${customer}'`);
    await reject(complete(r),undefined,'PT409');
    assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${customer}'`),'0');
    await reject(authorize(r),undefined,'PT409');
  });
  for(const [name,jwt] of [
    ['Admin',claims({sub:admin,session_id:asid})],['customer',claims({sub:customer,session_id:csid,aal:'aal1'})],
    ['forged AAL',claims({aal:'aal1'})],['foreign session',claims({session_id:asid})],['expired JWT',claims({exp:1})],
  ]) await fresh(`${name} cannot invite`,async()=>{
    const code=['foreign session','expired JWT'].includes(name)?'PT401':'PT403';
    await reject(rpc(),jwt,code);assert.equal(await auditCount(),'0');assert.equal(await role(),'User');
  });
  for(const [name,change,code] of [
    ['revoked session',`delete from auth.sessions where id='${sid}'`,'PT401'],
    ['missing factor',`delete from auth.mfa_factors where id='${factor}'`,'PT403'],
    ['unverified Owner',`update auth.users set email_confirmed_at=null where id='${owner}'`,'PT403'],
    ['pending Owner',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until) values('${owner}',now(),now()+interval '720 hours')`,'PT403'],
    ['removed scope',`delete from public."Location_to_Admin" where user_id='${owner}'`,'PT403'],
  ]) await fresh(`${name} after prepare denies authorize and completion`,async()=>{
    const r=await json();await db.query(change);
    await reject(authorize(r),undefined,code);await reject(complete(r),undefined,code);
    assert.equal(await role(),'User');assert.equal(await auditCount(),'1');
  });
  for(const target of [owner,other]) await fresh(`Owner target ${target} cannot be invited or resent`,async()=>{
    const email=target===owner?'owner@example.invalid':'other@example.invalid';
    await reject(rpc('invite',email));await reject(rpc('resend',null,[100],target));
    assert.equal(await auditCount(),'0');
  });
  for(const [label,change] of [
    ['pending',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until) values('${customer}',now(),now()+interval '720 hours')`],
    ['anonymous',`update auth.users set is_anonymous=true where id='${customer}'`],
    ['banned',`update auth.users set banned_until=now()+interval '1 day' where id='${customer}'`],
    ['deleted',`update auth.users set deleted_at=now() where id='${customer}'`],
  ]) await fresh(`${label} target cannot receive new access`,async()=>{
    await db.query(change);await reject(rpc(),undefined,label==='pending'?'PT403':'PT409');assert.equal(await role(),'User');
  });
  await fresh('ambiguous case-insensitive emails fail closed',async()=>{
    await db.query(`insert into auth.users(id,email) values('${invited}','CUSTOMER@example.invalid')`);
    await reject(rpc(),undefined,'PT409');assert.equal(await auditCount(),'0');
  });
  await fresh('Auth response target mismatch cannot assign another customer',async()=>{
    const r=await json();await reject(complete(r,admin),undefined,'PT409');assert.equal(await role(),'User');
  });
  for(const [label,change,code] of [
    ['email replaced',`update auth.users set email='replacement@example.invalid' where id='${customer}'`,'PT409'],
    ['target became Owner',`update public.profiles set roles='Owner' where id='${customer}'`,'PT403'],
    ['target requested deletion',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until) values('${customer}',now(),now()+interval '720 hours')`,'PT403'],
  ]) await fresh(`${label} after request cannot be granted or emailed`,async()=>{
    const r=await json();await db.query(change);
    await reject(authorize(r),undefined,code);await reject(complete(r),undefined,code);
    assert.equal(await auditCount(),'1');
  });
  await fresh('new email claimed by another Auth request before dispatch requires recheck',async()=>{
    const r=await json(rpc('invite','new@example.invalid'));
    await db.query(`insert into auth.users(id,email) values('${invited}','new@example.invalid')`);
    await reject(authorize(r),undefined,'PT409');assert.equal(await auditCount(),'1');
  });
  await fresh('service cannot record delivery without matching completed target',async()=>{
    const r=await json();await reject(delivered(r),{},'PT409','service_role');
    await json(complete(r));await reject(delivered(r,admin),{},'PT409','service_role');
    assert.equal(await auditCount(),'2');
  });
  await fresh('request is actor-bound; another eligible Owner cannot reuse it',async()=>{
    const r=await json();await db.query(`update public.profiles set roles='Owner' where id='${admin}'`);
    await reject(complete(r),claims({sub:admin,session_id:asid}),'PT409');assert.equal(await role(),'User');
  });
  await fresh('expired receipt cannot authorize email or assign access',async()=>{
    const id=await db.query(`insert into public.admin_audit_events(created_at,actor_id,actor_name,entity,entity_id,operation,location_ids,after_values)
      values(now()-interval '11 minutes','${owner}','Owner','team_onboarding','${customer}','requested',array[100],
      '{"mode":"invite","email":"customer@example.invalid","target_user_id":"${customer}"}') returning id;`);
    await reject(authorize({request_id:id}),undefined,'PT409');
    await reject(complete({request_id:id}),undefined,'PT409');assert.equal(await role(),'User');
  });
  await fresh('invalid actions, empty/foreign scopes and browser-forged delivery fail closed',async()=>{
    for(const sql of [rpc('other'),rpc('invite','bad'),rpc('invite','customer@example.invalid',[]),
      rpc('invite','customer@example.invalid',[null]),rpc('invite','customer@example.invalid',[0]),
      rpc('resend',null,[100,200],admin)]) await reject(sql,undefined,'22023');
    await reject(rpc('invite','customer@example.invalid',[200]));
    await reject(`insert into public.admin_audit_events(actor_name,entity,entity_id,operation)
      values('forged','team_onboarding','1','completed')`,undefined,'42501');
    assert.equal(await auditCount(),'0');
  });
  await fresh('customer promotion retains mandatory staff MFA and no password-only bypass',async()=>{
    const r=await json();await json(complete(r));
    const a=await json('select public.get_admission_status()',claims({sub:customer,session_id:csid,aal:'aal1'}));
    assert.equal(a.account_access,'restricted');assert.equal(a.next_step,'enroll_totp');
  });
  await fresh('lost-MFA recovery role guard still blocks promotion while old factors remain',async()=>{
    await db.query(`insert into auth.mfa_factors(id,user_id,factor_type,status,created_at) values('${uid(23)}','${customer}','totp','verified',now()-interval '1 day');`);
    await call(`select public.customer_mfa_recovery_request('prepare','${customer}','CASE-1',true,null)`);
    const r=await json();await assert.rejects(call(complete(r)));
    assert.equal(await role(),'User');assert.equal(await auditCount(),'1');
  });
  for(const [name,change] of [
    ['session revocation',`delete from auth.sessions where id='${sid}'`],
    ['factor removal',`delete from auth.mfa_factors where id='${factor}'`],
    ['location removal',`delete from public."Location_to_Admin" where user_id='${owner}'`],
    ['role demotion',`update public.profiles set roles='Admin' where id='${owner}'`],
    ['pending lifecycle',`insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until) values('${owner}',now(),now()+interval '720 hours')`],
  ]) await fresh(`profile wait rolls back assignment after ${name}`,async()=>{
    const r=await json(),locker=await cluster.connect(),waiter=await cluster.connect();
    try {
      await locker.query(`begin;select 1 from public.profiles where id='${customer}' for update;`);
      const failed=assert.rejects(waiter.query(`begin;${context()} ${complete(r)};commit;`));
      await blocked(db,waiter,locker);await db.query(change);await locker.query('commit;');await failed;
      assert.equal(await role(),'User');assert.equal(await auditCount(),'1');
    } finally {await locker.close();await waiter.close();}
  });
  await fresh('post-insert audit wait revalidates Owner and rolls back role/membership',async()=>{
    const r=await json();
    await db.query(`create function public.onboarding_test_wait() returns trigger language plpgsql as $$
      begin if new.entity='team_onboarding' and new.operation='completed' then perform pg_advisory_xact_lock(62134);end if;return null;end;$$;
      create trigger zz_onboarding_test_wait after insert on public.admin_audit_events for each row execute function public.onboarding_test_wait();`);
    const locker=await cluster.connect(),waiter=await cluster.connect();
    try {
      await locker.query('begin;select pg_advisory_xact_lock(62134);');
      const failed=assert.rejects(waiter.query(`begin;${context()} ${complete(r)};commit;`));
      await blocked(db,waiter,locker);await db.query(`delete from auth.sessions where id='${sid}'`);
      await locker.query('commit;');await failed;
      assert.equal(await role(),'User');assert.equal(await auditCount(),'1');
      assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${customer}'`),'0');
    } finally {
      await locker.close();await waiter.close();
      await db.query('drop trigger zz_onboarding_test_wait on public.admin_audit_events;drop function public.onboarding_test_wait();');
    }
  });
  await fresh('real concurrent completion grants once and keeps one immutable completion receipt',async()=>{
    const r=await json(),first=await cluster.connect(),second=await cluster.connect();
    try {
      await first.query(`begin;${context()} ${complete(r)};`);
      const pending=second.query(`begin;${context()} ${complete(r)};commit;`);
      await blocked(db,second,first);await first.query('commit;');await pending;
      assert.equal(await auditCount(),'2');
      assert.equal(await db.query(`select count(*) from public."Location_to_Admin" where user_id='${customer}'`),'1');
    } finally {await first.close();await second.close();}
  });
});
