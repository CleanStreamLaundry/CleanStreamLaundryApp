import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const baseline = process.env.CLEANSTREAM_CREDIT_BASELINE
  ? pathToFileURL(`${resolve(process.env.CLEANSTREAM_CREDIT_BASELINE)}/`)
  : new URL('../', import.meta.url);
const { disposableCluster, blocked } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', baseline));
const read = path => readFile(new URL(path, baseline), 'utf8');
const uid = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner = uid(1), customer = uid(3), session = uid(11), factor = uid(21), customerSession = uid(13);
const q = value => `'${String(value).replaceAll("'", "''")}'`;
const payload = 'b'.repeat(64);

test('atomic customer decision notice on actual canonical financial and mail prerequisites', { timeout: 180000 }, async t => {
  const cluster = await disposableCluster(t, process.env.PG_BIN), db = await cluster.connect();
  const migrate = async name => db.query(await read(`supabase/migrations/${name}.sql`));
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  await db.query("create role postgres superuser;set role postgres;set timezone='UTC';");
  await db.query(fixture[0]);
  for (const name of ['20260526010000_wallet_ledger_compliance','20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution','20260929231120_serialize_wallet_financial_writes']) await migrate(name);
  await db.query(fixture[1]);
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,add column is_anonymous boolean default false,
    add column banned_until timestamptz,add column deleted_at timestamptz,add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}',add column last_sign_in_at timestamptz,add column created_at timestamptz default now();
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;`);
  for (const name of ['20260929223124_protect_profile_authority','20260929234955_loyalty_policy_acceptance']) await migrate(name);
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const name of ['20260930005456_account_admission','20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership','20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await migrate(name);
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text,add column "Address" text,add column "Latitude" double precision,add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer,add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id text primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);`);
  for (const name of ['20260928135006_admin_portal_operations','20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting','20260930142406_admin_canonical_authorization',
    '20260930125527_newsletter_consent_mail_outbox','20260930175136_refund_request_notice_outbox',
    '20260930213049_account_lifecycle_mail_outbox']) await migrate(name);
  const preserved = () => db.query(`select jsonb_agg(jsonb_build_array(oid,pg_get_functiondef(oid),proacl) order by oid)
    from pg_proc where proname in ('resolve_refund_request','current_account_access','portal_staff_context',
      'mail_claim','mail_prepare','mail_finish','mail_record_webhook','mail_lifecycle_suppression')`);
  await migrate('20261001140307_mail_transactional_postal_split');
  const before = await preserved();
  await db.query(await readFile(new URL('../supabase/migrations/20260930220243_credit_decision_mail_outbox.sql', import.meta.url), 'utf8'));
  const run = async sql => { const c = await cluster.connect(); try { return await c.query(`set timezone='UTC';${sql}`); } finally { await c.close(); } };
  const context = (extra = {}) => `set local request.jwt.claim.sub='';set local role authenticated;
    set local request.jwt.claims=${q(JSON.stringify({ sub: owner, session_id: session, role: 'authenticated', aal: 'aal2', exp: Math.floor(Date.now()/1000)+3600, ...extra }))};`;
  const call = (sql, extra) => run(`begin;${context(extra)}${sql};commit;`).then(value => JSON.parse(value || 'null'));
  const decide = (id, decision = 'approved', note = 'Stored <note>') => call(`select public.admin_resolve_credit(${id},${q(decision)},${q(note)})`);
  const jobs = () => db.query("select coalesce(jsonb_agg(to_jsonb(o) order by created_at,id),'[]') from private.mail_outbox o").then(JSON.parse);
  const service = sql => run(`begin;set local role service_role;${sql};commit;`).then(value => value === 't' ? true : value === 'f' ? false : JSON.parse(value || 'null'));
  const claim = () => service('select public.mail_claim()');
  const prepare = o => service(`select public.mail_prepare('${o.id}','${o.lease_id}','${payload}',null,null)`);
  const finish = (o, result) => service(`select public.mail_finish('${o.id}','${o.lease_id}',${q(result)},${result === 'accepted' ? "'synthetic-provider'" : 'null'})`);
  const financial = () => db.query(`select jsonb_build_object(
    'claims',(select jsonb_agg(to_jsonb(r) order by refund_id) from public."Refunds" r),
    'wallets',(select jsonb_agg(to_jsonb(w) order by id) from public.wallet_accounts w),
    'ledger',(select jsonb_agg(to_jsonb(e) order by id) from public.wallet_ledger_entries e),
    'profiles',(select jsonb_agg(to_jsonb(p) order by id) from public.profiles p))`);
  const reset = async () => {
    await db.query(`truncate private.mail_webhook_event,private.mail_outbox,private.newsletter_consent,private.mail_suppression,private.account_lifecycle;
      truncate auth.users cascade;
      insert into private.mail_settings(singleton) values(true) on conflict do nothing;
      insert into auth.users(id,email,email_confirmed_at,created_at) values
        ('${owner}','owner@example.test',now(),now()-interval '2 days'),('${customer}','customer@example.test',now(),now()-interval '2 days');
      insert into public.profiles(id,roles) values('${owner}','Owner'),('${customer}','User');
      insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
        ('${session}','${owner}','aal2',now(),'${factor}'),('${customerSession}','${customer}','aal1',now(),null);
      insert into auth.mfa_factors(id,user_id,factor_type,status) values('${factor}','${owner}','totp','verified');
      insert into public."Locations"(id,"Name") values(100,'North'),(200,'South') on conflict do nothing;
      delete from public."Location_to_Admin";insert into public."Location_to_Admin" values('${owner}',100);
      insert into public."Machines"(id,"Location_ID","Name","Machine_type","Price") values(100,100,'A','Washer',4),(200,200,'B','Dryer',4)
        on conflict(id) do update set "Location_ID"=excluded."Location_ID";
      update private.mail_settings set enabled=true,rollout_at=now()-interval '1 hour',refund_notice_recipient='${owner}';`);
  };
  const seed = async (machine = 100) => {
    await db.query(`insert into public.cortina_vend_sessions(id,client_request_id,client_access_token_hash,machine_id,user_id,amount_cents,
      payment_method,channel,status,transaction_id) values('${uid(90)}','${uid(91)}','synthetic-hash',${machine},'${customer}',400,'card','web','started','synthetic-transaction');`);
    return Number(await db.query(`insert into public."Refunds"(user_id,transaction_id,amount,description)
      select '${customer}',id,4,'Synthetic claim' from public.transactions where cortina_vend_session_id='${uid(90)}' returning refund_id`));
  };
  const fresh = (name, action) => t.test(name, async () => { await reset(); await action(); });
  await t.test('migration preserves financial, lifecycle, retry and canonical authority bodies/ACLs', async () => {
    assert.equal(await preserved(), before);
    for (const role of ['anon','authenticated','service_role','supabase_auth_admin']) {
      assert.equal(await db.query(`select has_table_privilege('${role}','private.mail_outbox','INSERT')`), 'f');
      assert.equal(await db.query(`select has_function_privilege('${role}','private.mail_credit_decision_event()','EXECUTE')`), 'f');
    }
    assert.equal(await db.query("select has_function_privilege('authenticated','public.admin_resolve_credit(bigint,text,text)','EXECUTE')"), 't');
  });
  for (const decision of ['approved','denied']) await fresh(`${decision} atomically queues exact customer decision snapshot, never marks sent`, async () => {
    const id = await seed(), result = await decide(id, decision), [job] = await jobs();
    assert.equal(result.status, decision); assert.equal(result.notificationState, 'ready'); assert.equal(result.notificationSent, false);
    assert.equal(job.event_key, `loyalty_credit_${decision}/${id}`); assert.equal(job.kind, 'credit_decision');
    assert.equal(job.user_id, customer); assert.equal(job.email, 'customer@example.test'); assert.equal(job.consent_id, null);
    assert.deepEqual(job.credit_notice, { refund_id: String(id), transaction_id: String(result.transactionId), status: decision, amount_cents: 400, note: 'Stored <note>' });
    assert.equal(await db.query(`select notification_sent_at is null from public."Refunds" where refund_id=${id}`), 't');
    assert.equal(await db.query('select count(*) from private.voluntary_topup_refunds'), '0');
    assert.equal(await db.query('select coalesce(sum(promo_amount_cents),0)||\':\'||coalesce(sum(paid_amount_cents),0) from public.wallet_ledger_entries'), decision === 'approved' ? '400:0' : '0:0');
  });
  await fresh('parallel same decision retries preserve one credit and one event', async () => {
    const id = await seed(); await Promise.all([decide(id),decide(id),decide(id)]);
    assert.equal((await jobs()).length, 1); assert.equal(await db.query('select count(*) from public.wallet_ledger_entries'), '1');
    await assert.rejects(() => decide(id,'denied'), /already approved/); assert.equal((await jobs()).length, 1);
  });
  await fresh('rollback removes both promo decision and queued notice', async () => {
    const id = await seed(); await run(`begin;${context()}select public.admin_resolve_credit(${id},'approved','Rollback');rollback;`);
    assert.deepEqual(await jobs(), []); assert.equal(await db.query('select count(*) from public.wallet_ledger_entries'), '0');
    assert.equal(await db.query(`select status from public."Refunds" where refund_id=${id}`), 'pending');
  });
  await fresh('disabled delivery retains durable post-rollout intent, not a provider call', async () => {
    const id = await seed(); await db.query('update private.mail_settings set enabled=false');
    assert.equal((await decide(id)).notificationState, 'ready'); assert.equal(await claim(), null);
    await db.query('update private.mail_settings set enabled=true'); assert.equal((await claim()).kind, 'credit_decision');
  });
  await fresh('pre-rollout decision is never backfilled by an idempotent retry', async () => {
    const id = await seed(); await db.query("update private.mail_settings set rollout_at=now()+interval '1 day'");
    assert.equal((await decide(id)).notificationState, 'not_queued');
    await db.query("update private.mail_settings set rollout_at=now()-interval '1 day'");
    assert.equal((await decide(id)).alreadyResolved, true); assert.deepEqual(await jobs(), []);
  });
  await fresh('legacy sent evidence remains readable without backfilling or rewriting timestamps', async () => {
    const id = await seed(); await db.query("update private.mail_settings set rollout_at=now()+interval '1 day'");
    await decide(id); await db.query(`update public."Refunds" set notification_sent_at=now() where refund_id=${id}`);
    const before = await financial(), receipt = await decide(id);
    assert.equal(receipt.notificationState, 'legacy_sent'); assert.equal(receipt.notificationSent, true);
    assert.equal(await financial(), before); assert.deepEqual(await jobs(), []);
  });
  await fresh('unknown mail outcome stays parked through decision retry; credit is not repeated', async () => {
    const id = await seed(); await decide(id); const job = await claim(); assert.equal(await prepare(job), true); await finish(job,'uncertain');
    const before = await financial(), receipt = await decide(id);
    assert.equal(receipt.notificationState, 'uncertain'); assert.equal(receipt.notificationSent, false);
    assert.equal(await financial(), before); assert.equal(await claim(), null); assert.equal((await jobs()).length, 1);
  });
  await fresh('rate-limit notification retry is independent of decision and keeps permanent job identity', async () => {
    const id = await seed(); await decide(id); const before = await financial(), first = await claim();
    assert.equal(await prepare(first), true); await finish(first,'rate_limited');
    await db.query("update private.mail_outbox set next_at=now()-interval '1 second'");
    const retry = await claim(); assert.equal(retry.id, first.id); assert.equal(await prepare(retry), true);
    await finish(retry,'accepted'); assert.equal(await financial(), before);
    assert.equal((await decide(id)).notificationState, 'accepted'); assert.equal((await decide(id)).notificationSent, true);
  });
  for (const [name, sql] of [
    ['email change', `update auth.users set email='other@example.test' where id='${customer}'`],
    ['unverified', `update auth.users set email_confirmed_at=null where id='${customer}'`],
    ['ban', `update auth.users set banned_until=now()+interval '1 day' where id='${customer}'`],
    ['bounce', "insert into private.mail_suppression values('customer@example.test','email.bounced',now())"],
    ['stored note changed', 'update public."Refunds" set admin_note=\'Superseded\''],
    ['resolution changed', "update public.\"Refunds\" set resolved_at=resolved_at+interval '1 second'"],
  ]) await fresh(`${name} after lease suppresses stale customer notice`, async () => {
    const id = await seed(); await decide(id); const job = await claim(); await db.query(sql);
    assert.equal(await prepare(job), false); assert.equal((await jobs())[0].state, 'suppressed');
  });
  await fresh('failed notification cannot hide or roll back a committed decision', async () => {
    const id = await seed(); await decide(id); const before = await financial(), job = await claim();
    assert.equal(await prepare(job), true); await finish(job,'failed');
    const receipt = await decide(id); assert.equal(receipt.notificationState, 'failed'); assert.equal(receipt.success, true);
    assert.equal(await financial(), before); assert.equal(await claim(), null);
  });
  await fresh('superseded decision snapshot is not sent or automatically replaced', async () => {
    const id = await seed(); await decide(id); const job = await claim();
    await db.query(`update public."Refunds" set status='denied' where refund_id=${id}`);
    assert.equal(await prepare(job), false); assert.equal((await jobs()).length, 1);
    assert.equal((await jobs())[0].credit_notice.status, 'approved');
  });
  await fresh('unsubscribe does not suppress a necessary decision notice', async () => {
    const id = await seed(); await decide(id);
    await call('select public.newsletter_withdraw()', { sub: customer, session_id: customerSession, aal: 'aal1' });
    assert.equal((await jobs())[0].state, 'ready'); assert.equal(await prepare(await claim()), true);
  });
  await fresh('approved status without matching promo-ledger evidence cannot send a credit claim', async () => {
    const id = await seed(); await db.query(`update public."Refunds" set status='approved',resolved_at=now(),resolved_by='${owner}' where refund_id=${id}`);
    assert.equal((await jobs())[0].state, 'suppressed'); assert.equal(await claim(), null);
    assert.equal(await db.query('select count(*) from public.wallet_ledger_entries'), '0');
  });
  await fresh('foreign location and lost current factor remain authoritative before any queue write', async () => {
    const id = await seed(200); await assert.rejects(() => decide(id), /access denied/i);
    await db.query(`insert into public."Location_to_Admin" values('${owner}',200);delete from auth.mfa_factors where id='${factor}'`);
    await assert.rejects(() => decide(id), /enroll_totp/); assert.deepEqual(await jobs(), []);
  });
  await fresh('revocation during enqueue mail-lock wait rolls back decision, ledger and event', async () => {
    const id = await seed(), holder = await cluster.connect(), waiter = await cluster.connect();
    try {
      await holder.query('begin;select private.mail_lock();');
      const outcome = waiter.query(`begin;${context()}select public.admin_resolve_credit(${id},'approved','Pending');commit;`)
        .then(value => ({ value }), error => ({ error }));
      await blocked(db,waiter,holder); await db.query(`delete from auth.sessions where id='${session}'`);
      await holder.query('commit;'); const result = await outcome; assert.equal(result.error?.code, 'PT401');
      assert.deepEqual(await jobs(), []); assert.equal(await db.query('select count(*) from public.wallet_ledger_entries'), '0');
      assert.equal(await db.query(`select status from public."Refunds" where refund_id=${id}`), 'pending');
    } finally { await holder.close(); await waiter.close(); }
  });
  await fresh('mail completion never waits on a held refund row or writes its sent timestamp', async () => {
    const id = await seed(); await decide(id); const job = await claim(); assert.equal(await prepare(job), true);
    const holder = await cluster.connect();
    try {
      await holder.query(`begin;select 1 from public."Refunds" where refund_id=${id} for update`);
      await finish(job,'accepted'); assert.equal((await jobs())[0].state, 'accepted');
      assert.equal(await db.query(`select notification_sent_at is null from public."Refunds" where refund_id=${id}`), 't');
    } finally { await holder.query('rollback'); await holder.close(); }
  });
  await fresh('request alert remains separate and becomes stale when the claim is decided', async () => {
    const id = await seed(), txn = Number(await db.query(`select transaction_id from public."Refunds" where refund_id=${id}`));
    await call(`select public.enqueue_refund_request_notice(${txn})`, { sub: customer, session_id: customerSession, aal: 'aal1' });
    const alert = await claim(); assert.equal(alert.kind, 'refund_request');
    await decide(id,'denied'); assert.equal(await prepare(alert), false);
    const rows = await jobs(); assert.equal(rows.length, 2);
    assert.equal(rows[0].event_key, `loyalty_credit_requested/${id}`);
    assert.equal(rows[1].event_key, `loyalty_credit_denied/${id}`);
  });
  await fresh('lifecycle scheduled/restore notices retain current-snapshot behavior', async () => {
    await call('select public.request_account_deletion()', { sub: customer, session_id: customerSession, aal: 'aal1' });
    const scheduled = await claim(); assert.equal(scheduled.kind, 'account_deletion_scheduled');
    await db.query(`insert into auth.sessions(id,user_id,aal,created_at) values('${uid(14)}','${customer}','aal1',clock_timestamp())`);
    await call('select public.restore_account()', { sub: customer, session_id: uid(14), aal: 'aal1' });
    assert.equal(await prepare(scheduled), false); assert.equal((await claim()).kind, 'account_restored');
  });
});
