import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const sha = value => createHash('sha256').update(value).digest('hex');
const inputs = [
  ['20260930130013', 'push_token_registration', 'ec3075684bd75c87978ef0ed44b77f970d656b906c2c33ba95e037985010b657'],
  ['20261001011048', 'push_registration_bounds', 'aab8796f25db121884c828adff41cb3c26fe00975b290894565287540d97ffea'],
];
assert.equal(sha(readFileSync(new URL('activation-push.sql', root))),
  '16bd17417cb65f61f498b21bf2abcad95e4f739728ee416875fe1d21de803ce6');
assert.equal(new Set(inputs.map(([version]) => version)).size, 2);
const values = inputs.map(([version, name, hash]) => {
  const source = readFileSync(new URL(`supabase/migrations/${version}_${name}.sql`, root), 'utf8');
  assert.equal(sha(source), hash);
  assert(!source.includes('$push_source$') && !source.includes('$push_history$'));
  return `    ('${version}', '${name}', '${hash}', $push_source$${source}$push_source$)`;
}).join(',\n');

const sql = `-- GENERATED by scripts/build-push-history.mjs; history metadata ONLY.
-- Target dnuuhupoxjtwqzaqylvb DEVELOPMENT; initial absence preflight711b97.
-- Execute ONLY after QA source acceptance, schema commit and matching postflight.
-- Exactly two complete reviewed source files stored as inert text, NEVER executed.
-- Original per-file transaction wrappers are provenance only. No schema replay.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
LOCK TABLE supabase_migrations.schema_migrations IN SHARE ROW EXCLUSIVE MODE;

DO $push_history$
DECLARE
  entry record;
  inserted_count integer := 0;
BEGIN
  IF (SELECT count(*) FROM pg_catalog.pg_attribute
      WHERE attrelid = 'supabase_migrations.schema_migrations'::regclass
        AND NOT attisdropped
        AND ((attname IN ('version', 'name') AND atttypid = 'text'::regtype)
          OR (attname = 'statements' AND atttypid = 'text[]'::regtype))) <> 3
    OR NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_index i
      JOIN pg_catalog.pg_attribute a
        ON a.attrelid = i.indrelid AND a.attname = 'version'
      WHERE i.indrelid = 'supabase_migrations.schema_migrations'::regclass
        AND i.indisunique AND i.indisvalid AND i.indnkeyatts = 1
        AND i.indpred IS NULL AND i.indexprs IS NULL AND i.indkey[0] = a.attnum
    ) THEN
    RAISE EXCEPTION 'Unexpected migration history shape or missing unique version index';
  END IF;
  FOR entry IN SELECT * FROM (VALUES
${values}
  ) AS approved(version, name, source_sha256, source_sql)
  LOOP
    IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations h WHERE h.version = entry.version) THEN
      RAISE EXCEPTION 'History version % already exists; entire transaction aborted', entry.version;
    END IF;
    IF encode(sha256(convert_to(entry.source_sql, 'UTF8')), 'hex') <> entry.source_sha256 THEN
      RAISE EXCEPTION 'History source digest mismatch for %', entry.version;
    END IF;
    INSERT INTO supabase_migrations.schema_migrations (version, name, statements)
      VALUES (entry.version, entry.name, ARRAY[entry.source_sql]::text[]);
    inserted_count := inserted_count + 1;
  END LOOP;
  IF inserted_count <> 2 THEN
    RAISE EXCEPTION 'Expected exactly two history entries';
  END IF;
END;
$push_history$;
COMMIT;

-- Exact two-version metadata receipt; no customer/token rows or RPC execution.
SELECT version, name, cardinality(statements) AS stored_source_files,
       encode(sha256(convert_to(statements[1], 'UTF8')), 'hex') AS source_sha256
FROM supabase_migrations.schema_migrations
WHERE version IN ('20260930130013', '20261001011048') ORDER BY version;
`;
const output = fileURLToPath(new URL('record-push-history.sql', root));
writeFileSync(output, sql);
console.log(JSON.stringify({ output, sha256: sha(sql), versions: inputs.length }));
