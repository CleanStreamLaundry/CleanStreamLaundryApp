import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

const sourceRoot = process.env.CUSTOMER_RECORD_APP_ROOT;
assert(!sourceRoot || isAbsolute(sourceRoot), 'Prerequisite root must be absolute');
const active = sourceRoot ? pathToFileURL(`${sourceRoot}/`) : new URL('../', import.meta.url);
const { disposableCluster } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', active));
const read = (p) => readFile(new URL(p, active), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await readFile(new URL('../supabase/migrations/20260930220649_customer_record_read_admission.sql', import.meta.url), 'utf8');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const user = uid(1), other = uid(2), owner = uid(3), admin = uid(4);
const sid = uid(11), osid = uid(13), asid = uid(14), factor = uid(21);
const quote = (v) => `'${String(v).replaceAll("'", "''")}'`;
const claims = (extra = {}) => ({sub:user, session_id:sid, role:'authenticated', aal:'aal1',
  exp:Math.floor(Date.now()/1000)+3600, ...extra});
const ownerClaims = () => claims({sub:owner, session_id:osid, aal:'aal2'});
const adminClaims = () => claims({sub:admin, session_id:asid, aal:'aal2'});
const context = (jwt = claims(), role = 'authenticated') =>
  `set local request.jwt.claims=${quote(JSON.stringify(jwt))}; set local request.jwt.claim.sub=''; set local role ${role};`;
const signature = 'private.portal_record_access(text,jsonb)';
const tables = ['transactions', '"Refunds"', '"Maintenance"'];

test('ordinary customer record reads reuse canonical admission without changing financial exceptions', {timeout:180000}, async (t) => {
  const cluster = await disposableCluster(t, process.env.PG_BIN), db = await cluster.connect();
  const run = async (sql) => {
    const s = await cluster.connect();
    try { return await s.query(sql); } finally { await s.close(); }
  };
  const call = (sql, jwt, role) => run(`begin; ${context(jwt, role)} ${sql}; commit;`);
  const json = async (sql, jwt, role) => JSON.parse(await call(sql, jwt, role));
  const rejects = (sql, code, jwt, role) => assert.rejects(call(sql, jwt, role), (e) => {
    assert.equal(e.code, code, e.message); return true;
  });
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length, 2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance','20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution','20260929231120_serialize_wallet_financial_writes']) await db.query(await migration(n));
  await db.query(`grant execute on function public.is_admin_or_owner() to authenticated;
    create trigger handle_transaction after insert on public.transactions for each row execute function public.update_user_balance();`);
  for (const n of ['20260807195409_configure_dryer_time_options','20260922224735_cortina_price_array_selectors',
    '20260928132533_link_cortina_transaction_history']) await db.query(await migration(n));
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false,add column banned_until timestamptz,
    add column deleted_at timestamptz,add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}',add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;`);
  for (const n of ['20260929223124_protect_profile_authority','20260929234955_loyalty_policy_acceptance']) await db.query(await migration(n));
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission','20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership','20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text,add column "Address" text,add column "Latitude" double precision,add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer,add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id bigint primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);`);
  for (const n of ['20260928135006_admin_portal_operations','20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting','20260930142406_admin_canonical_authorization',
    '20260930171558_human_wallet_spend_admission','20260930184955_wallet_read_admission',
    '20260930190143_complaint_admission_recheck','20260930202731_customer_mfa_recovery',
    '20260930213402_canonical_admin_onboarding']) await db.query(await migration(n));
  // Broad permissive legacy SELECTs must still intersect the existing portal scope.
  for (const table of tables) await db.query(`grant select on public.${table} to authenticated;
    create policy fixture_legacy_read on public.${table} for select to authenticated using(true);`);
  await db.query(`reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status,created_at) on auth.mfa_factors to postgres;
    alter role postgres nosuperuser bypassrls;`);
  const metadata = () => db.query(`select jsonb_build_array(oid,proowner,proacl,prosecdef,provolatile,proconfig,
    pg_get_function_arguments(oid),pg_get_function_result(oid)) from pg_proc where oid='${signature}'::regprocedure;`);
  const otherFunctions = () => db.query(`select jsonb_object_agg(oid::regprocedure::text,
    jsonb_build_array(pg_get_functiondef(oid),proacl,proowner)) from pg_proc
    where pronamespace in('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace)
      and prokind='f' and oid<>'${signature}'::regprocedure;`);
  const policies = () => db.query('select jsonb_agg(to_jsonb(p) order by oid) from pg_policy p;');
  const rows = () => db.query(`select jsonb_build_object(
    'transactions',(select jsonb_agg(to_jsonb(x) order by id) from public.transactions x),
    'refunds',(select jsonb_agg(to_jsonb(x) order by refund_id) from public."Refunds" x),
    'reports',(select jsonb_agg(to_jsonb(x) order by maint_id) from public."Maintenance" x),
    'wallet',(select jsonb_agg(to_jsonb(x) order by id) from public.wallet_accounts x),
    'loads',(select jsonb_agg(to_jsonb(x) order by id) from public.wallet_loads x),
    'ledger',(select jsonb_agg(to_jsonb(x) order by id) from public.wallet_ledger_entries x),
    'profiles',(select jsonb_agg(to_jsonb(x) order by id) from public.profiles x));`);
  const reset = async () => {
    await db.query(`truncate public."Maintenance"; truncate auth.users cascade;
      delete from public."Location_to_Admin";
      insert into auth.users(id,email_confirmed_at) values('${user}',now()),('${other}',now()),('${owner}',now()),('${admin}',now());
      insert into public.profiles(id,roles) values('${user}','User'),('${other}','User'),('${owner}','Owner'),('${admin}','Admin');
      insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
        ('${sid}','${user}','aal1',now()-interval '1 hour',null),
        ('${uid(12)}','${other}','aal1',now()-interval '1 hour',null),
        ('${osid}','${owner}','aal2',now()-interval '1 hour','${uid(23)}'),
        ('${asid}','${admin}','aal2',now()-interval '1 hour','${uid(24)}');
      insert into auth.mfa_factors(id,user_id,factor_type,status) values
        ('${uid(23)}','${owner}','totp','verified'),('${uid(24)}','${admin}','totp','verified');
      insert into public."Locations"(id,"Name") values(100,'North'),(200,'South') on conflict do nothing;
      insert into public."Location_to_Admin"(user_id,location_id) values('${owner}',100),('${admin}',100);
      insert into public."Maintenance"(maint_id,user_id,location_id,description) values
        (1,'${user}',100,'Own report'),(2,'${other}',200,'Other location'),
        (3,'${owner}',null,'Unattributed'),(4,'${admin}',100,'Staff own report');
      update private.topup_refund_policy set enabled_at=now()-interval '3 days';`);
    for (const [i, target] of [user,other,owner,admin].entries()) await db.query(`
      insert into public.transactions(id,user_id,amount,type,description) values(${i+1},'${target}',10,'laundry','Legacy vend');
      insert into public."Refunds"(refund_id,user_id,transaction_id,amount,description)
        values(${i+1},'${target}',${i+1},10,'Machine claim');`);
  };
  const fresh = (name, fn) => t.test(name, async () => { await reset(); await fn(); });
  const counts = async (jwt = claims()) => {
    const values = [];
    for (const table of tables) values.push(Number(await call(`select count(*) from public.${table}`, jwt)));
    return values;
  };
  const denied = async (jwt) => assert.deepEqual(await counts(jwt), [0,0,0]);
  await reset();
  const before = {metadata:await metadata(), functions:await otherFunctions(), policies:await policies(), rows:await rows()};
  await t.test('missing legacy authorization prerequisite aborts atomically', async () => {
    const body = candidate.replace(/^begin;$/m, '').replace(/^commit;$/m, '');
    await assert.rejects(run(`begin; set local role postgres;
      alter function private.portal_record_access_before_authorization(text,jsonb) rename to fixture_missing;
      ${body} commit;`), (e) => { assert.equal(e.code,'55000'); return true; });
    assert.equal(await otherFunctions(), before.functions);
  });
  await db.query(`set role postgres; ${candidate} reset role;`);
  await t.test('only wrapper body changes; OID ACL owner policies other functions and rows are preserved', async () => {
    assert.equal(await metadata(), before.metadata);
    assert.equal(await otherFunctions(), before.functions);
    assert.equal(await policies(), before.policies);
    assert.equal(await rows(), before.rows);
  });
  await fresh('eligible pre-terms customer retains only own records without recursion', async () => {
    assert.deepEqual(await counts(), [1,1,1]);
    assert.equal((await json('select public.get_admission_status()')).next_step, 'review_terms');
    for (const table of tables) assert.equal(await call(`select count(*) from public.${table} where user_id='${other}'`),'0');
  });
  await fresh('stale terms do not invent a Home requirement for ordinary support reads', async () => {
    await db.query(`update public.profiles set loyalty_policy_version='old',loyalty_policy_accepted_at=now() where id='${user}';`);
    assert.deepEqual(await counts(), [1,1,1]);
  });
  for (const [name, sql] of [
    ['unverified email',`update auth.users set email_confirmed_at=null where id='${user}'`],
    ['anonymous user',`update auth.users set is_anonymous=true where id='${user}'`],
    ['banned user',`update auth.users set banned_until=now()+interval '1 day' where id='${user}'`],
    ['Auth-deleted user',`update auth.users set deleted_at=now() where id='${user}'`],
    ['unknown role',`update public.profiles set roles=null where id='${user}'`],
    ['new staff without factor',`update public.profiles set roles='Admin' where id='${user}'`],
  ]) await fresh(`${name} cannot read own records`, async () => {
    await db.query(sql); const snapshot = await rows(); await denied(); assert.equal(await rows(), snapshot);
  });
  for (const [name, sql] of [
    ['revoked session',`delete from auth.sessions where id='${sid}'`],
    ['expired session',`update auth.sessions set not_after=now()-interval '1 second' where id='${sid}'`],
  ]) await fresh(`${name} fails closed`, async () => {
    await db.query(sql);
    for (const table of tables) await rejects(`select count(*) from public.${table}`, 'PT401');
  });
  for (const [name, change] of [['expired JWT',{exp:1}],['foreign session',{session_id:uid(12)}],
    ['wrong JWT role',{role:'service_role'}],['unsupported assurance',{aal:'aal3'}]]) {
    await fresh(`${name} cannot disclose records`, async () => {
      for (const table of tables) await rejects(`select count(*) from public.${table}`, 'PT401', claims(change));
    });
  }
  await fresh('current optional TOTP requires bound verified factor and AAL2', async () => {
    await db.query(`insert into auth.mfa_factors(id,user_id,factor_type,status) values('${factor}','${user}','totp','verified');
      update auth.sessions set aal='aal2',factor_id='${factor}' where id='${sid}';`);
    await denied(); assert.deepEqual(await counts(claims({aal:'aal2'})), [1,1,1]);
    await db.query(`update auth.sessions set factor_id='${uid(23)}' where id='${sid}';`);
    await denied(claims({aal:'aal2'}));
  });
  for (const days of [0,31]) await fresh(`pending deletion denies ordinary records at age ${days} days`, async () => {
    await call('select public.request_account_deletion()');
    if (days) await db.query(`update private.account_lifecycle set deletion_requested_at=now()-interval '31 days',restore_until=now()-interval '1 day';`);
    await denied();
  });
  await fresh('explicit fresh-session restoration reopens reads, not the old session', async () => {
    await call('select public.request_account_deletion()');
    await db.query(`insert into auth.sessions(id,user_id,aal,created_at) values('${uid(15)}','${user}','aal1',clock_timestamp());`);
    const jwt = claims({session_id:uid(15)});
    await call('select public.restore_account()',jwt);
    assert.deepEqual(await counts(jwt),[1,1,1]);
    for (const table of tables) await rejects(`select count(*) from public.${table}`, 'PT401');
  });
  await fresh('Owner/Admin existing role and location scope remain exact', async () => {
    assert.deepEqual(await counts(ownerClaims()), [4,4,3]);
    assert.deepEqual(await counts(adminClaims()), [1,1,2]);
    assert.equal(await call('select count(*) from public."Maintenance" where location_id=200',adminClaims()),'0');
    await denied(claims({sub:owner,session_id:osid,aal:'aal1'}));
    await denied(claims({sub:admin,session_id:asid,aal:'aal1'}));
  });
  await fresh('pending staff cannot use own-record shortcut or assigned location', async () => {
    await call('select public.request_account_deletion()',adminClaims()); await denied(adminClaims());
  });
  await fresh('mandatory recovery reenrollment fence applies before own-record shortcut', async () => {
    await db.query(`insert into private.customer_mfa_recovery(user_id,actor_id,support_case,factor_ids)
      values('${user}','${owner}','synthetic-support-case',array['${factor}']::uuid[]);`);
    for (const table of tables) await rejects(`select count(*) from public.${table}`, 'PT401');
    await db.query(`insert into auth.sessions(id,user_id,aal,created_at)
      values('${uid(16)}','${user}','aal1',clock_timestamp());`);
    await denied(claims({session_id:uid(16)}));
  });
  await fresh('pending customer refund exception works while ordinary reads remain denied', async () => {
    await db.query(`select public.record_wallet_load_from_stripe('${user}',2000,'pi_record_refund');
      select public.record_topup_refund_provenance('pi_record_refund','${user}',2000,now()-interval '1 minute','evt_record_refund',false,null);`);
    const loadId = await db.query(`select id from public.wallet_loads where stripe_payment_intent_id='pi_record_refund';`);
    await call('select public.request_account_deletion()'); await denied();
    const receipt = await json(`select public.request_voluntary_topup_refund(${loadId})`);
    assert.equal(receipt.customer_id,user); assert.equal(receipt.principal_cents,2000);
    assert.deepEqual(await json('select public.list_voluntary_topup_refunds()'),[receipt]);
    await json(`select public.review_voluntary_topup_refund('${receipt.id}','approve')`,ownerClaims());
    const service = {role:'service_role'};
    assert.equal((await json(`select public.prepare_voluntary_topup_refund('${receipt.id}')`,service,'service_role')).amount,2000);
    const settled = await json(`select public.reconcile_voluntary_topup_refund('${receipt.id}',
      're_record','succeeded','pi_record_refund',2000,'usd',false)`,service,'service_role');
    assert.equal(settled.status,'succeeded'); await denied();
  });
  await fresh('service late settlement remains idempotent for pending customer', async () => {
    await call('select public.request_account_deletion()');
    const sql = `select public.record_wallet_load_from_stripe('${user}',1500,'pi_record_late')`;
    const first = await call(sql,{role:'service_role'},'service_role');
    assert.equal(await call(sql,{role:'service_role'},'service_role'),first);
    assert.equal(await db.query("select count(*) from public.wallet_loads where stripe_payment_intent_id='pi_record_late';"),'1');
    await denied();
  });
  await fresh('staff complaint/support and global-money revokes retain their existing contracts', async () => {
    await db.query(`select public.record_wallet_load_from_stripe('${user}',1000,'pi_record_support');`);
    const wallet = await db.query(`select id from public.wallet_accounts where user_id='${user}';`);
    await call('select public.request_account_deletion()');
    await call(`select public.record_deleted_account_complaint('${wallet}','Preserved support','denied')`,ownerClaims());
    assert.equal(await db.query('select count(*) from public.deleted_account_complaints;'),'1');
    for (const fn of ['admin_adjust_wallet(uuid,integer,integer,integer,text)',
      'admin_set_wallet_status(uuid,text,text)','admin_record_legal_cash_redemption(uuid,integer,text,text)']) {
      for (const role of ['anon','authenticated','service_role']) {
        assert.equal(await db.query(`select has_function_privilege('${role}','public.${fn}','execute');`),'f');
      }
    }
    assert.equal(await otherFunctions(),before.functions);
  });
});
