import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.env.INVENTORY_PRIVILEGES_APP_ROOT;
assert(root && isAbsolute(root), 'Set INVENTORY_PRIVILEGES_APP_ROOT to the accepted read-only app');
const active = pathToFileURL(`${root}/`);
const { disposableCluster } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', active));
const read = (p) => readFile(new URL(p, active), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await readFile(new URL('../supabase/migrations/20261001103350_restrict_inventory_client_maintenance_privileges.sql', import.meta.url), 'utf8');
const body = candidate.replace(/^begin;$/m, '').replace(/^commit;$/m, '');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner = uid(1), staff = uid(2), customer = uid(3);
const claims = (n = 1) => ({ sub: uid(n), session_id: uid(n + 10), role: 'authenticated',
  aal: n === 3 ? 'aal1' : 'aal2', exp: Math.floor(Date.now() / 1000) + 3600 });
const literal = (v) => `'${String(v).replaceAll("'", "''")}'`;
const tables = [
  { name: 'Locations', sql: 'public."Locations"', key: 'id' },
  { name: 'washer_size_rates', sql: 'public.washer_size_rates', key: 'id' },
  { name: 'cortina_machine_config', sql: 'public.cortina_machine_config', key: 'machine_id' },
];
const targets = tables.map(({ sql }) => `${literal(sql)}::regclass`).join(',');

test('fixed inventory maintenance privilege removal preserves canonical operations', { timeout: 180000 }, async (t) => {
  const cluster = await disposableCluster(t, process.env.PG_BIN), db = await cluster.connect();
  const run = async (sql) => {
    const session = await cluster.connect();
    try { return await session.query(sql); } finally { await session.close(); }
  };
  const as = (sql, role = 'authenticated', jwt = claims()) => run(`begin;
    set local request.jwt.claims=${literal(JSON.stringify(jwt))};
    set local request.jwt.claim.sub=''; set local role ${role}; ${sql}; rollback;`);
  const denied = (sql, role) => assert.rejects(as(sql, role),
    (e) => { assert.equal(e.code, '42501', e.message); return true; });
  const readOutcome = async (sql, role) => {
    try { return { result: await as(sql, role) }; } catch (e) { return { code: e.code }; }
  };

  // Reuse the accepted synthetic inventory/canonical-staff prerequisites, not old suites.
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length, 2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance', '20260803150427_cortina_qr_remote_vend',
    '20260804015500_cortina_rls_policy_cleanup', '20260807191723_harden_refund_resolution',
    '20260929231120_serialize_wallet_financial_writes', '20260807195409_configure_dryer_time_options',
    '20260922224735_cortina_price_array_selectors', '20260928132533_link_cortina_transaction_history']) {
    await db.query(await migration(n));
  }
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false, add column banned_until timestamptz,
    add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table public."Location_to_Admin" enable row level security;
    grant select on public."Location_to_Admin" to anon,authenticated;
    create policy legacy_membership_public_read on public."Location_to_Admin" for select to public using(true);`);
  for (const n of ['20260929223124_protect_profile_authority', '20260929234955_loyalty_policy_acceptance']) {
    await db.query(await migration(n));
  }
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission', '20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership', '20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text, add column "Address" text, add column "Latitude" double precision, add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer, add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id bigint primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);
    alter table public."Machines" enable row level security;
    alter table public."Locations" enable row level security;
    grant select on public."Machines",public."Locations" to anon,authenticated;
    create policy legacy_machine_public_read on public."Machines" for select to public using(true);
    create policy legacy_machine_block_update on public."Machines" as restrictive for update to public using(false) with check(false);
    create policy legacy_location_public_read on public."Locations" for select to public using(true);`);
  for (const n of ['20260928135006_admin_portal_operations', '20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting', '20260930142406_admin_canonical_authorization',
    '20260930202731_customer_mfa_recovery', '20260930213402_canonical_admin_onboarding',
    '20261001101347_restrict_machine_client_maintenance_privileges']) await db.query(await migration(n));
  await db.query(`revoke all on function public.request_account_deletion() from public,anon,authenticated,service_role;
    revoke all on function public.is_admin_or_owner() from public,anon;
    grant execute on function public.is_admin_or_owner() to authenticated;
    grant select,truncate,references,trigger,maintain on public."Locations",public.washer_size_rates,public.cortina_machine_config to anon,authenticated;
    reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status,created_at) on auth.mfa_factors to postgres;
    alter role postgres nosuperuser bypassrls;
    insert into auth.users(id,email_confirmed_at) values('${owner}',now()),('${staff}',now()),('${customer}',now());
    insert into public.profiles(id,roles) values('${owner}','Owner'),('${staff}','Admin'),('${customer}','User');
    insert into auth.mfa_factors(id,user_id,factor_type,status) values
      ('${uid(21)}','${owner}','totp','verified'),('${uid(22)}','${staff}','totp','verified');
    insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
      ('${uid(11)}','${owner}','aal2',now()-interval '1 hour','${uid(21)}'),
      ('${uid(12)}','${staff}','aal2',now()-interval '1 hour','${uid(22)}'),
      ('${uid(13)}','${customer}','aal1',now()-interval '1 hour',null);
    insert into public."Locations"(id,"Name","Address") values(100,'North','Public address'),(200,'South','Public address');
    insert into public."Location_to_Admin"(user_id,location_id) values('${owner}',100),('${staff}',100);
    insert into public.washer_size_rates(id,location_id,size_label,capacity_kg,price_cents)
      values(100,100,'10 kg',10,100);
    insert into public."Machines"(id,"Location_ID","Name","Machine_type","Price","Runtime","Status","Weight_kg",
      service_reason,service_updated_by) values(100,100,'Dryer','Dryer',0.25,5,'idle',10,'Synthetic staff note','${owner}');
    create schema fixture_probe; grant usage,create on schema fixture_probe to anon,authenticated;
    create function fixture_probe.noop() returns trigger language plpgsql as $$begin return new; end;$$;`);

  const permissions = () => db.query(`select jsonb_build_object(
    'tables',(select jsonb_agg(jsonb_build_array(oid,relacl) order by oid) from pg_class where oid in (${targets})),
    'columns',(select jsonb_agg(jsonb_build_array(attrelid,attname,attacl) order by attrelid,attnum)
      from pg_attribute where attrelid in (${targets}) and attnum>0 and not attisdropped));`);
  const invariant = () => db.query(`select jsonb_build_object(
    'locations',(select jsonb_agg(to_jsonb(x) order by id) from public."Locations" x),
    'rates',(select jsonb_agg(to_jsonb(x) order by id) from public.washer_size_rates x),
    'config',(select jsonb_agg(to_jsonb(x) order by machine_id) from public.cortina_machine_config x),
    'machines',(select jsonb_agg(to_jsonb(x) order by id) from public."Machines" x),
    'audit',(select jsonb_agg(to_jsonb(x) order by id) from public.admin_audit_events x),
    'functions',(select jsonb_agg(jsonb_build_array(p.oid,pg_get_functiondef(p.oid),p.proacl,p.proowner) order by p.oid)
      from pg_proc p where p.pronamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace) and p.prokind='f'),
    'policies',(select jsonb_agg(to_jsonb(p) order by oid) from pg_policy p),
    'triggers',(select jsonb_agg(to_jsonb(g) order by oid) from pg_trigger g),
    'tables',(select jsonb_agg(jsonb_build_array(c.oid,c.relowner,c.relrowsecurity,c.relforcerowsecurity,
      case when c.oid not in (${targets}) then c.relacl end) order by c.oid)
      from pg_class c where c.relnamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace)),
    'effective_table',(select jsonb_agg(jsonb_build_array(c.oid,r,p,has_table_privilege(r,c.oid,p)) order by c.oid,r,p)
      from pg_class c cross join unnest(array['anon','authenticated','service_role','postgres']) r
      cross join unnest(array['SELECT','INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p
      where c.oid in (${targets}) and (r in ('service_role','postgres') or p in ('SELECT','INSERT','UPDATE','DELETE'))),
    'effective_columns',(select jsonb_agg(jsonb_build_array(a.attrelid,r,a.attname,p,has_column_privilege(r,a.attrelid,a.attnum,p)) order by a.attrelid,r,a.attnum,p)
      from pg_attribute a cross join unnest(array['anon','authenticated','service_role','postgres']) r
      cross join unnest(array['SELECT','INSERT','UPDATE','REFERENCES']) p
      where a.attrelid in (${targets}) and a.attnum>0 and not a.attisdropped
        and (r in ('service_role','postgres') or p<>'REFERENCES')));`);
  const originalPermissions = await permissions(), originalInvariant = await invariant();
  const effectiveDenied = `select bool_and(not has_table_privilege(r,c.oid,p))
    and (select bool_and(not has_column_privilege(rr,a.attrelid,a.attnum,'REFERENCES'))
      from pg_attribute a cross join unnest(array['anon','authenticated']) rr
      where a.attrelid in (${targets}) and a.attnum>0 and not a.attisdropped)
    from pg_class c cross join unnest(array['anon','authenticated']) r
    cross join unnest(array['TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p where c.oid in (${targets});`;
  const beforeReads = new Map();
  for (const table of tables) for (const role of ['anon','authenticated']) {
    beforeReads.set(`${table.name}/${role}`, await readOutcome(`select ${table.key} from ${table.sql} order by ${table.key}`, role));
  }
  const failedInstall = async (setup, code = '42501') => {
    await assert.rejects(run(`begin; ${setup} set local role postgres; ${body} commit;`),
      (e) => { assert.equal(e.code, code, e.message); return true; });
    assert.equal(await permissions(), originalPermissions);
    assert.equal(await invariant(), originalInvariant);
  };

  for (const table of tables) await t.test(`${table.name} baseline matches hosted SELECT and Dxtm without IUD`, async () => {
    for (const role of ['anon','authenticated']) {
      assert.equal(await db.query(`select bool_and(has_table_privilege('${role}','${table.sql}',p))
        from unnest(array['SELECT','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p;`), 't');
      assert.equal(await db.query(`select bool_and(not has_table_privilege('${role}','${table.sql}',p))
        from unnest(array['INSERT','UPDATE','DELETE']) p;`), 't');
    }
  });
  for (const [name, setup] of [
    ['Locations inherited TRUNCATE', 'grant truncate on public."Locations" to fixture_parent; grant fixture_parent to anon with inherit true,set false;'],
    ['rates inherited column REFERENCES', 'grant references(id) on public.washer_size_rates to fixture_parent; grant fixture_parent to authenticated with inherit true,set false;'],
    ['config SET-only MAINTAIN', 'grant maintain on public.cortina_machine_config to fixture_parent; grant fixture_parent to authenticated with inherit false,set true;'],
  ]) await t.test(`${name} fails without changing other roles or tables`, async () => {
    await failedInstall(`create role fixture_parent; ${setup}`);
    assert.equal(await db.query("select count(*) from pg_roles where rolname='fixture_parent';"), '0');
  });
  await t.test('unexpected client bypass fails atomically', async () => { await failedInstall('alter role anon bypassrls;'); });
  await t.test('last-table RLS failure rolls back earlier table revokes', async () => {
    await failedInstall('alter table public.cortina_machine_config disable row level security;', '55000');
  });
  await t.test('last-table dependent grant failure never cascades and rolls back all three', async () => {
    await failedInstall(`create role fixture_recipient; set local role postgres;
      grant trigger on public.cortina_machine_config to authenticated with grant option;
      set local role authenticated; grant trigger on public.cortina_machine_config to fixture_recipient; reset role;`, '2BP01');
  });
  await t.test('last-table PUBLIC-only service column rights are protected atomically', async () => {
    await failedInstall(`set local role postgres; revoke references on public.cortina_machine_config from service_role;
      grant references(machine_id) on public.cortina_machine_config to public; reset role;`);
  });
  await t.test('successful explicit rollback restores all original grants', async () => {
    assert.equal(await run(`begin; set local role postgres; ${body} ${effectiveDenied} rollback;`), 't');
    assert.equal(await permissions(), originalPermissions);
    assert.equal(await invariant(), originalInvariant);
  });
  await t.test('install removes only PUBLIC and client Dxtm plus column REFERENCES on fixed three', async () => {
    const grants = tables.map(({ sql, key }) => `grant truncate,references,trigger,maintain on ${sql} to public;
      grant references(${key}) on ${sql} to public,anon,authenticated;`).join('\n');
    await db.query(`set role postgres; ${grants} ${candidate} reset role;`);
    assert.equal(await db.query(effectiveDenied), 't');
    assert.equal(await invariant(), originalInvariant);
    assert.equal(await db.query(`select count(*) from pg_class c, lateral aclexplode(c.relacl) a
      where c.oid in (${targets}) and a.grantee=0 and a.privilege_type in ('TRUNCATE','REFERENCES','TRIGGER','MAINTAIN');`), '0');
  });
  for (const table of tables) for (const role of ['anon','authenticated']) {
    await t.test(`${table.name} ${role} preserves reads and denies four maintenance operations`, async () => {
      assert.deepEqual(await readOutcome(`select ${table.key} from ${table.sql} order by ${table.key}`, role), beforeReads.get(`${table.name}/${role}`));
      for (const sql of [
        `truncate table ${table.sql}`,
        `create table fixture_probe.attempt(id bigint references ${table.sql}(${table.key}))`,
        `create trigger fixture_attempt before update on ${table.sql} for each row execute function fixture_probe.noop()`,
        `reindex table ${table.sql}`,
      ]) await denied(sql, role);
    });
  }
  for (const [name, action, payload, verify, serviceUpdate] of [
    ['Locations', 'createLocation', { input: { Name: 'New site', Address: 'Synthetic address', Latitude: 40, Longitude: -86 } },
      `select count(*) from public."Locations" where "Name"='New site'`,
      `update public."Locations" set "Name"='Service site' where id=100; select "Name" from public."Locations" where id=100`],
    ['washer_size_rates', 'saveRate', { rate: { id: 100, location_id: 100, size_label: '10 kg', capacity_kg: 10, price_cents: 150, is_active: true } },
      'select count(*) from public.washer_size_rates where id=100 and price_cents=150',
      "update public.washer_size_rates set size_label='Service rate' where id=100; select size_label from public.washer_size_rates where id=100"],
    ['cortina_machine_config', 'saveConfig', { config: { machine_id: 100, nayax_terminal_id: 'synthetic-device', environment: 'sandbox', is_enabled: false } },
      "select count(*) from public.cortina_machine_config where machine_id=100 and nayax_terminal_id='synthetic-device' and not is_enabled",
      "update public.cortina_machine_config set nayax_terminal_id='Service device' where machine_id=100; select nayax_terminal_id from public.cortina_machine_config where machine_id=100"],
  ]) await t.test(`${name} canonical Owner operation and service write remain permitted with Admin denied`, async () => {
    const sql = `select public.admin_portal_request(${literal(action)},${literal(JSON.stringify(payload))})`;
    const output = await as(`${sql}; ${verify}`);
    assert.equal(output.split('\n').at(-1), '1');
    await assert.rejects(as(sql, 'authenticated', claims(2)), (e) => {
      assert.equal(e.code, '42501'); assert.match(e.message, /Owner access required/); return true;
    });
    assert.match(await as(serviceUpdate, 'service_role', {}), /^Service /);
    assert.equal(await invariant(), originalInvariant);
  });
  await t.test('final effective denial preserves Machines ACL and deletion hold', async () => {
    assert.equal(await db.query(effectiveDenied), 't');
    assert.equal(await db.query(`select bool_and(not has_function_privilege(r,'public.request_account_deletion()','EXECUTE'))
      from unnest(array['anon','authenticated','service_role']) r;`), 't');
    assert.equal(await invariant(), originalInvariant);
  });
});
