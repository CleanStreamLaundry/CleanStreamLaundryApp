create role postgres nologin nosuperuser bypassrls;
create role anon nologin inherit;
create role authenticated nologin inherit;
create role service_role nologin bypassrls;
grant usage, create on schema public to postgres;
grant usage on schema public to anon, authenticated, service_role;
revoke create on schema public from public, anon, authenticated, service_role;
create schema auth authorization postgres;
grant usage on schema auth to anon, authenticated, service_role;

set role postgres;
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
create type public."Roles" as enum ('User', 'Admin', 'Owner');
create table public.profiles (
  id uuid primary key, roles public."Roles" default 'User'
);
create table public."Locations" (
  id bigint generated by default as identity primary key,
  "Address" text, "Name" text, "Details" text,
  "Latitude" double precision, "Longitude" double precision,
  "Hours" text not null default '6:00 AM - 10:00 PM',
  "OpenHour" smallint not null default 6, "CloseHour" smallint not null default 22,
  "AfterHoursAvailable" boolean not null default false
);
create table public."Location_to_Admin" (
  id bigint generated by default as identity primary key,
  location_id bigint references public."Locations"(id),
  user_id uuid references public.profiles(id) on update cascade on delete cascade
);
create index location_membership_location_fixture on public."Location_to_Admin"(location_id);
create index location_membership_user_fixture on public."Location_to_Admin"(user_id);
alter table public."Location_to_Admin" enable row level security;
create policy membership_select_fixture on public."Location_to_Admin"
  for select to public using (true);
create policy membership_insert_fixture on public."Location_to_Admin"
  for insert to public with check (exists (
    select 1 from public.profiles p where p.id = auth.uid()
      and p.roles in ('Admin', 'Owner')
  ));
create policy membership_delete_fixture on public."Location_to_Admin"
  for delete to public using (exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.roles = 'Owner'
  ));
grant all on public."Location_to_Admin" to anon, authenticated, service_role;
grant select on public.profiles, public."Locations" to anon, authenticated;
grant all on public.profiles, public."Locations" to service_role;
-- Sequence privileges are fixture support, not claimed live observations.
grant usage, select on all sequences in schema public to anon, authenticated, service_role;

