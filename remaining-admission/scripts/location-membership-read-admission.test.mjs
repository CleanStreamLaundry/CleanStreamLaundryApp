import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.env.MEMBERSHIP_READ_APP_ROOT;
assert(root && isAbsolute(root), 'Set MEMBERSHIP_READ_APP_ROOT to the accepted read-only app');
const active = pathToFileURL(`${root}/`);
const { disposableCluster } = await import(new URL('scripts/test-support/policy-admission-pg.mjs', active));
const read = (p) => readFile(new URL(p, active), 'utf8');
const migration = (n) => read(`supabase/migrations/${n}.sql`);
const candidate = await readFile(new URL('../supabase/migrations/20261001094740_deny_anonymous_location_membership.sql', import.meta.url), 'utf8');
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const owner = uid(1), staff = uid(2), customer = uid(3);
const claims = (n = 1) => ({ sub: uid(n), session_id: uid(n + 10), role: 'authenticated',
  aal: n === 3 ? 'aal1' : 'aal2', exp: Math.floor(Date.now() / 1000) + 3600 });
const literal = (v) => `'${String(v).replaceAll("'", "''")}'`;
const table = 'public."Location_to_Admin"';

test('anonymous membership closure preserves canonical staff scope and public browsing', { timeout: 180000 }, async (t) => {
  const cluster = await disposableCluster(t, process.env.PG_BIN), db = await cluster.connect();
  const run = async (sql) => {
    const session = await cluster.connect();
    try { return await session.query(sql); } finally { await session.close(); }
  };
  const as = (sql, role = 'authenticated', jwt = claims(), setup = '') => run(`begin;
    ${setup} set local request.jwt.claims=${literal(JSON.stringify(jwt))};
    set local request.jwt.claim.sub=''; set local role ${role}; ${sql}; rollback;`);
  const count = (role, jwt, setup) => as(`select count(*) from ${table}`, role, jwt, setup);

  // Reuse the accepted admin fixture prerequisites, not their unrelated test suites.
  const fixture = (await read('supabase/tests/wallet_financial_locking.fixture.sql')).split('-- AFTER_BASELINE_MIGRATIONS');
  assert.equal(fixture.length, 2);
  await db.query('set client_min_messages=warning; create role postgres superuser; set role postgres;');
  await db.query(fixture[0]);
  for (const n of ['20260526010000_wallet_ledger_compliance', '20260803150427_cortina_qr_remote_vend',
    '20260807191723_harden_refund_resolution', '20260929231120_serialize_wallet_financial_writes',
    '20260807195409_configure_dryer_time_options', '20260922224735_cortina_price_array_selectors',
    '20260928132533_link_cortina_transaction_history']) await db.query(await migration(n));
  await db.query(`alter table auth.users add column email_confirmed_at timestamptz,
    add column is_anonymous boolean default false, add column banned_until timestamptz,
    add column deleted_at timestamptz, add column raw_user_meta_data jsonb default '{}',
    add column raw_app_meta_data jsonb default '{}', add column last_sign_in_at timestamptz;
    alter table public.profiles add column created_at timestamptz default now();
    alter table ${table} enable row level security;
    grant select on ${table} to anon,authenticated;
    create policy legacy_membership_public_read on ${table} for select to public using(true);`);
  for (const n of ['20260929223124_protect_profile_authority', '20260929234955_loyalty_policy_acceptance']) {
    await db.query(await migration(n));
  }
  await db.query(await read('supabase/tests/account_admission.fixture.sql'));
  for (const n of ['20260930005456_account_admission', '20260930013417_enforce_profile_terms_admission',
    '20260930024142_protect_location_membership', '20260930063923_recoverable_account_deletion',
    '20260930125554_voluntary_topup_refunds']) await db.query(await migration(n));
  await db.query(`alter table public."Locations" alter column id add generated by default as identity,
    add column "Name" text, add column "Address" text, add column "Latitude" double precision, add column "Longitude" double precision;
    alter table public."Machines" add column "Runtime" integer, add column "Status" text;
    alter table public."Refunds" add column date timestamptz default now();
    create table public."Maintenance"(maint_id bigint primary key,user_id uuid,category text,description text,
      created_at timestamptz default now(),location text,image_data text);
    alter table public."Machines" enable row level security;
    alter table public."Locations" enable row level security;
    grant select on public."Machines",public."Locations" to anon,authenticated;
    create policy legacy_machine_public_read on public."Machines" for select to public using(true);
    create policy legacy_location_public_read on public."Locations" for select to public using(true);
    -- A historical nullable assignment precedes the installed audit trigger.
    insert into ${table}(user_id,location_id) values(null,null);`);
  for (const n of ['20260928135006_admin_portal_operations', '20260928151021_admin_operations_extensions',
    '20260930131557_admin_collection_reporting', '20260930142406_admin_canonical_authorization',
    '20260930202731_customer_mfa_recovery', '20260930213402_canonical_admin_onboarding']) {
    await db.query(await migration(n));
  }
  await db.query(`revoke all on function public.request_account_deletion() from public,anon,authenticated,service_role;
    revoke all on function public.is_admin_or_owner() from public,anon;
    grant execute on function public.is_admin_or_owner() to authenticated;
    reset role; grant usage,create on schema public to postgres;
    grant select(id,is_anonymous,deleted_at,banned_until,email_confirmed_at),update(id) on auth.users to postgres;
    grant select(id,user_id,aal,factor_id,not_after,created_at) on auth.sessions to postgres;
    grant select(id,user_id,factor_type,status,created_at) on auth.mfa_factors to postgres;
    alter role postgres nosuperuser bypassrls;
    insert into auth.users(id,email_confirmed_at) values('${owner}',now()),('${staff}',now()),('${customer}',now());
    insert into public.profiles(id,roles) values('${owner}','Owner'),('${staff}','Admin'),('${customer}','User');
    insert into auth.mfa_factors(id,user_id,factor_type,status) values
      ('${uid(21)}','${owner}','totp','verified'),('${uid(22)}','${staff}','totp','verified');
    insert into auth.sessions(id,user_id,aal,created_at,factor_id) values
      ('${uid(11)}','${owner}','aal2',now()-interval '1 hour','${uid(21)}'),
      ('${uid(12)}','${staff}','aal2',now()-interval '1 hour','${uid(22)}'),
      ('${uid(13)}','${customer}','aal1',now()-interval '1 hour',null);
    insert into public."Locations"(id,"Name","Address") values(100,'North','Public address'),(200,'South','Public address');
    insert into ${table}(user_id,location_id) values('${owner}',100),('${staff}',200),('${customer}',100);
    insert into public."Machines"(id,"Location_ID","Name","Machine_type","Price") values(100,100,'Dryer','Dryer',0.25);`);

  const snapshot = () => db.query(`select jsonb_build_object(
    'rows',(select jsonb_agg(to_jsonb(m) order by user_id,location_id) from ${table} m),
    'relations',(select jsonb_agg(jsonb_build_array(c.oid,c.relacl,c.relowner,c.relrowsecurity,c.relforcerowsecurity) order by c.oid)
      from pg_class c where c.relnamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace)),
    'functions',(select jsonb_agg(jsonb_build_array(p.oid,pg_get_functiondef(p.oid),p.proacl,p.proowner) order by p.oid)
      from pg_proc p where p.pronamespace in ('public'::regnamespace,'private'::regnamespace,'auth'::regnamespace) and p.prokind='f'),
    'policies',(select jsonb_agg(to_jsonb(p) order by p.oid) from pg_policy p where p.polname<>'portal_membership_no_anon'),
    'columns',(select jsonb_agg(jsonb_build_array(a.attrelid,a.attname,a.attacl) order by a.attrelid,a.attnum)
      from pg_attribute a join pg_class c on c.oid=a.attrelid where c.relnamespace='public'::regnamespace and a.attnum>0 and not a.attisdropped),
    'audit',(select jsonb_agg(to_jsonb(a) order by id) from public.admin_audit_events a));`);
  const before = await snapshot();
  await t.test('baseline reproduces anonymous exposure despite canonical authenticated restriction', async () => {
    assert.equal(await count('anon', {}), '4');
    assert.equal(await count('authenticated', claims(1)), '1');
    assert.equal(await count('authenticated', claims(2)), '1');
    assert.equal(await count('authenticated', claims(3)), '0');
    assert.equal(await db.query("select has_function_privilege('anon','public.is_admin_or_owner()','EXECUTE');"), 'f');
  });
  await t.test('missing canonical policy prerequisite aborts without partial changes', async () => {
    const body = candidate.replace(/^begin;$/m, '').replace(/^commit;$/m, '');
    await assert.rejects(run(`begin; set local role postgres;
      alter policy portal_membership_direct_self on ${table} rename to fixture_missing;
      ${body} commit;`), (e) => { assert.equal(e.code, '55000'); return true; });
    assert.equal(await snapshot(), before);
  });
  await db.query(`set role postgres; ${candidate} reset role;`);
  await t.test('only anonymous restrictive policy added; grants records audit and canonical bodies unchanged', async () => {
    assert.equal(await snapshot(), before);
    assert.equal(await db.query(`select count(*) from pg_policy where polrelid='${table}'::regclass
      and polname='portal_membership_no_anon' and polcmd='r' and not polpermissive
      and polroles=array['anon'::regrole::oid] and pg_get_expr(polqual,polrelid)='false';`), '1');
    assert.equal(await db.query("select not rolsuper and rolbypassrls from pg_roles where rolname='postgres';"), 't');
  });
  await t.test('signed-out direct SELECT and location join reveal no staff assignments', async () => {
    assert.equal(await count('anon', {}), '0');
    assert.equal(await as(`select count(*) from public."Locations" l join ${table} m on m.location_id=l.id`, 'anon', {}), '0');
    assert.equal(await as(`select count(*) from ${table} where user_id='${owner}'`, 'anon', {}), '0');
  });
  await t.test('extra permissive policy and table/column grants cannot reopen anonymous membership', async () => {
    assert.equal(await count('anon', {}, `grant select on ${table} to public,anon;
      grant select(user_id) on ${table} to public,anon;
      create policy fixture_extra_read on ${table} for select to anon using(true);`), '0');
    assert.equal(await snapshot(), before);
  });
  await t.test('eligible Owner and Admin keep only their own assignments without customer terms or recursion', async () => {
    for (const n of [1, 2]) {
      assert.equal(await count('authenticated', claims(n)), '1');
      assert.equal(await as(`select count(*) from ${table} where user_id<>'${uid(n)}'`, 'authenticated', claims(n)), '0');
      const status = JSON.parse(await as('select public.get_admission_status()', 'authenticated', claims(n)));
      assert.equal(status.account_access, 'eligible');
      assert.equal(status.next_step, 'review_terms');
    }
    assert.equal(await count('authenticated', claims(3)), '0');
  });
  for (const [name, setup, jwt] of [
    ['pending deletion', `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
      values('${owner}',now(),now()+interval '720 hours');`, claims()],
    ['expired pending deletion', `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
      values('${owner}',now()-interval '721 hours',now()-interval '1 hour');`, claims()],
    ['revoked session', `delete from auth.sessions where id='${uid(11)}';`, claims()],
    ['missing MFA', `delete from auth.mfa_factors where id='${uid(21)}';`, claims()],
    ['AAL1 token', '', { ...claims(), aal: 'aal1' }],
    ['cross-account session', '', { ...claims(), session_id: uid(12) }],
  ]) await t.test(`${name} cannot read own assignments or fall back to anonymous access`, async () => {
    assert.equal(await count('authenticated', jwt, setup), '0');
    assert.equal(await count('anon', {}, setup), '0');
  });
  await t.test('public locations and displayed machine price stay readable signed-out and pending', async () => {
    const sql = `select jsonb_build_array((select count(*) from public."Locations"),
      (select "Price" from public."Machines" where id=100))`;
    assert.deepEqual(JSON.parse(await as(sql, 'anon', {})), [2, 0.25]);
    assert.deepEqual(JSON.parse(await as(sql, 'authenticated', claims(),
      `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
        values('${owner}',now(),now()+interval '720 hours');`)), [2, 0.25]);
  });
  await t.test('canonical location RPC remains caller-bound and denies pending while actor-taking RPC stays held', async () => {
    const result = JSON.parse(await as("select public.admin_portal_request('locations')"));
    assert.deepEqual(result.map((r) => r.id), [100]);
    await assert.rejects(as("select public.admin_portal_request('locations')", 'authenticated', claims(),
      `insert into private.account_lifecycle(user_id,deletion_requested_at,restore_until)
        values('${owner}',now(),now()+interval '720 hours');`), (e) => { assert.equal(e.code, 'PT403'); return true; });
    await assert.rejects(as(`select public.admin_portal_data('${owner}','locations','{}')`),
      (e) => { assert.equal(e.code, '42501'); return true; });
  });
  await t.test('trusted service reads and canonical definer membership writes remain available', async () => {
    assert.equal(await count('service_role', {}), '4');
    const created = JSON.parse(await as(`select public.admin_portal_request('createLocation',
      '{"input":{"Name":"Fixture only","Address":"Synthetic","Latitude":40,"Longitude":-86}}')`));
    assert.equal(created.Name, 'Fixture only');
    assert.equal(await snapshot(), before);
  });
  await t.test('direct writes remain denied and deletion hold is never released', async () => {
    for (const role of ['anon', 'authenticated']) {
      await assert.rejects(as(`insert into ${table}(user_id,location_id) values('${owner}',200)`, role),
        (e) => { assert.equal(e.code, '42501'); return true; });
    }
    assert.equal(await db.query(`select bool_and(not has_function_privilege(r,
      'public.request_account_deletion()','EXECUTE')) from unnest(array['anon','authenticated','service_role']) r;`), 't');
    assert.equal(await snapshot(), before);
  });
});
