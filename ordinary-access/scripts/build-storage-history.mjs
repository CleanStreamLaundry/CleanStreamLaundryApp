import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const path = '/Users/jamaki604/CleanStreamProjects/CleanStreamLaundryApp/supabase/migrations/20260930165320_maintenance_attachment_access.sql';
const version = '20260930165320';
const name = 'maintenance_attachment_access';
const sourceHash = 'fc0f5f1697314d785eee18afdca9b5dad8e5e3af1be3ab1adb2b6ad161ce4d54';
const sha = (value) => createHash('sha256').update(value).digest('hex');
const source = readFileSync(path, 'utf8');
assert.equal(sha(source), sourceHash);
assert(!source.includes('$storage_source$') && !source.includes('$storage_history$'));

// Same history-only lock/shape/unique-version/hash guards as accepted C/D recording.
const sql = `-- GENERATED by scripts/build-storage-history.mjs; metadata only.
-- Project dnuuhupoxjtwqzaqylvb DEVELOPMENT. Helper already installed exit0/7d8631.
-- Prior absence preflight e4870f. Source SHA256 ${sourceHash}.
-- ONE verbatim reviewed source file stored as inert text, NEVER executed.
-- No policy/bucket/object changes, schema replay, overwrite or history deletion.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
LOCK TABLE supabase_migrations.schema_migrations IN SHARE ROW EXCLUSIVE MODE;

DO $storage_history$
DECLARE
  source_sql constant text := $storage_source$${source}$storage_source$;
  inserted_count integer;
BEGIN
  IF (SELECT count(*) FROM pg_catalog.pg_attribute
      WHERE attrelid = 'supabase_migrations.schema_migrations'::regclass
        AND NOT attisdropped
        AND ((attname IN ('version', 'name') AND atttypid = 'text'::regtype)
          OR (attname = 'statements' AND atttypid = 'text[]'::regtype))) <> 3
    OR NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_index i
      JOIN pg_catalog.pg_attribute a
        ON a.attrelid = i.indrelid AND a.attname = 'version'
      WHERE i.indrelid = 'supabase_migrations.schema_migrations'::regclass
        AND i.indisunique AND i.indisvalid AND i.indnkeyatts = 1
        AND i.indpred IS NULL AND i.indexprs IS NULL AND i.indkey[0] = a.attnum
    ) THEN
    RAISE EXCEPTION 'Unexpected migration history shape or missing unique version index';
  END IF;
  IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '${version}') THEN
    RAISE EXCEPTION 'History version ${version} already exists; entire transaction aborted';
  END IF;
  IF encode(sha256(convert_to(source_sql, 'UTF8')), 'hex') <> '${sourceHash}' THEN
    RAISE EXCEPTION 'History source digest mismatch for ${version}';
  END IF;
  INSERT INTO supabase_migrations.schema_migrations (version, name, statements)
    VALUES ('${version}', '${name}', ARRAY[source_sql]::text[]);
  GET DIAGNOSTICS inserted_count = ROW_COUNT;
  IF inserted_count <> 1 THEN
    RAISE EXCEPTION 'Expected exactly one history entry';
  END IF;
END;
$storage_history$;
COMMIT;

-- One history metadata receipt only, no customer/object data.
SELECT version, name, cardinality(statements) AS stored_source_files,
       encode(sha256(convert_to(statements[1], 'UTF8')), 'hex') AS source_sha256
FROM supabase_migrations.schema_migrations WHERE version = '${version}';
`;
const output = fileURLToPath(new URL('../record-storage-history.sql', import.meta.url));
writeFileSync(output, sql);
console.log(JSON.stringify({ output, sha256: sha(sql), versions: 1, sourceHash }));
